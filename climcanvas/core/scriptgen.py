def script_header(kind: str) -> list[str]:
    """生成スクリプト冒頭の行 (1 行 docstring + 空行)。kind は主語。

    生成物の権利関係 (利用者に帰属、AGPL の対象外) はスクリプト内には書かず
    LICENSE.exception と README で示す (2026-09-18 判断)。
    """
    return [f'"""{kind} generated by ClimCanvas {__version__}."""', ""]


def _assemble_script(gen: "_ScriptBuilder", figure_config: dict,
                     dataset_paths: dict[str, str],
                     dataset_renames: dict[str, dict[str, str]] | None,
                     datasets: dict[str, xr.Dataset], *, header_kind: str,
                     imports_first: list[str] = (), imports_last: list[str] = ()) -> str:
    """ヘッダ・import・外部 cmap・埋め込み関数・open_dataset・本文を結合して
    スクリプト文字列にする (静止画・アニメーション共通)。

    import は gen の needs_* フラグから必要なものだけ出す。imports_first /
    imports_last はアニメーション用の標準ライブラリ・PIL の import。
    """
    custom_cmaps = _collect_custom_cmaps(figure_config)
    ext_pkg_keys = external_cmaps.packages_used_in(figure_config)
    ext_imports, ext_setup = external_cmaps.script_setup_lines(
        ext_pkg_keys, figure_config)

    imports = list(imports_first)
    if gen.needs_mdates:
        imports.append("import matplotlib.dates as mdates")
    if gen.needs_mpath:
        imports.append("import matplotlib.path as mpath")
    imports.append("import matplotlib.pyplot as plt")
    if gen.needs_mticker:
        imports.append("import matplotlib.ticker as mticker")
    if custom_cmaps or external_cmaps.needs_matplotlib(ext_pkg_keys):
        imports.append("import matplotlib as mpl")
    if custom_cmaps or gen.needs_mcolors:
        imports.append("import matplotlib.colors as mcolors")
    if gen.needs_numpy:
        imports.append("import numpy as np")
    if gen.needs_pandas:
        imports.append("import pandas as pd")
    imports.append("import xarray as xr")
    if gen.needs_ccrs:
        imports.append("import cartopy.crs as ccrs")
    if gen.needs_feature:
        imports.append("import cartopy.feature as cfeature")
    if gen.needs_inversion_guard:
        imports.append("from cartopy.mpl.geoaxes import InterProjectionTransform")
    imports.extend(imports_last)
    imports.extend(ext_imports)

    open_lines = _open_dataset_lines(dataset_paths, dataset_renames, datasets)
    cmap_lines = _custom_cmap_registration_lines(custom_cmaps)
    # 反転ガード・第2軸との値揃えの関数本体は render のものをそのまま埋め込む (1対1)
    guard_lines = ([inspect.getsource(drop_inverting_contour_rings), ""]
                   if gen.needs_inversion_guard else [])
    guard_lines += ([inspect.getsource(align_twin_ylim), ""]
                    if gen.needs_twin_align else [])

    header = script_header(header_kind)
    return "\n".join(
        header + imports + [""] + ext_setup + cmap_lines + guard_lines + open_lines + [""] + gen.body
    ) + "\n"


def generate_script(figure_config: dict, datasets: dict[str, xr.Dataset],
                    dataset_paths: dict[str, str], *,
                    figure_output: str = "figure.png", figure_dpi: int = 300,
                    include_save: bool = True, include_show: bool = True,
                    figure_transparent: bool = False, figure_tight: bool = True,
                    figure_facecolor: str | None = None,
                    dataset_renames: dict[str, dict[str, str]] | None = None) -> str:
    """図を再現するスタンドアロンスクリプトの文字列を返す。

    datasets はレイヤーが実際に使う次元の確認と座標の昇順・降順の判定に使う。
    dataset_paths は生成スクリプトに埋め込むファイルパス (絶対/相対は呼び出し側で決める)。
    figure_output の拡張子が出力形式を決める (PNG / EPS / PDF / SVG、仕様23章)。
    figure_transparent=True で背景透明、figure_facecolor で画像全体の背景色 (両者は
    排他。アプリ側で二者択一)、figure_tight=False で bbox_inches="tight" を
    付けない (アプリ側の出力設定と一致させる)。
    dataset_renames は `{dsid: {old_name: new_name}}`。open_dataset 直後に `.rename(...)` を
    挿入する (アプリ側の座標整合チェックで dim 名を canonical に揃えた場合に使う)。
    """
    gen = _ScriptBuilder()
    _emit_figure_lines(gen, figure_config)
    _emit_panels(gen, figure_config, datasets)
    gen.body.append("")
    if include_save:
        save_args = [repr(figure_output), f"dpi={figure_dpi!r}"]
        if figure_tight:
            save_args.append('bbox_inches="tight"')
        if figure_transparent:
            save_args.append("transparent=True")
        elif figure_facecolor is not None:
            save_args.append(f"facecolor={figure_facecolor!r}")
        gen.body.append(f"fig.savefig({', '.join(save_args)})")
    if include_show:
        gen.body.append("plt.show()")
    return _assemble_script(gen, figure_config, dataset_paths, dataset_renames, datasets,
                            header_kind="Reproduction script")


def _emit_figure_lines(gen: "_ScriptBuilder", figure_config: dict) -> None:
    """plt.figure(...) と余白調整 (subplots_adjust) を emit する。

    render_figure の figure 生成部と1対1対応 (subplot 追加前に余白を適用)。
    """
    fig_cfg = figure_config.get("figure", {})
    figsize = tuple(fig_cfg.get("figsize", (10.0, 6.0)))
    dpi = fig_cfg.get("dpi", 100)
    if fig_cfg.get("font_family"):
        # render.apply_font_family と1対1対応 (全テキストに効く)
        gen.body.append(
            f"plt.rcParams['font.family'] = {fig_cfg['font_family']!r}")
    gen.body.append(f"fig = plt.figure(figsize=({figsize[0]!r}, {figsize[1]!r}), dpi={dpi!r})")
    adjust = subplots_adjust_kwargs(figure_config)
    if adjust:
        gen.body.append(f"fig.subplots_adjust({_fmt_kwargs_inline(adjust)})")


def _emit_panels(gen: "_ScriptBuilder", figure_config: dict, datasets: dict) -> None:
    """全パネルをグリッド位置とともに順に emit する (render_figure のループと1対1対応)。

    複数パネルのときだけ区切りコメントを挿入する (単一パネルの生成スクリプトは
    従来と同一のテキストを保つ)。共通カラーバーが ON のときは各パネルの ax を
    `axes` リストに集め、最後に全パネル共通のカラーバーを描く (仕様22.5)。
    """
    panels = figure_config["panels"]
    nrows, ncols, cells = panel_subplot_specs(figure_config)
    # 行・列の比率指定時のみ GridSpec 経由 (render の分岐と1対1。未指定の
    # 生成スクリプトは従来テキストのまま)
    ratios = grid_ratio_kwargs(figure_config, nrows, ncols)
    if ratios:
        kw = ", ".join(f"{k}={v!r}" for k, v in ratios.items())
        gen.body.append(f"gs = fig.add_gridspec({nrows}, {ncols}, {kw})")
    multi = len(panels) > 1
    shared_cbar = shared_colorbar_config(figure_config)
    collect_axes = bool(shared_cbar.get("show"))
    if collect_axes:
        gen.body.append("axes = []")
    for i, panel in enumerate(panels):
        gen.subplot = (nrows, ncols, cells[i])
        if ratios:
            r0, r1, c0, c1 = cell_grid_bounds(cells[i], ncols)
            gen.subplot_gs = (f"gs[{r0}, {c0}]" if (r0, c0) == (r1, c1)
                              else f"gs[{r0}:{r1 + 1}, {c0}:{c1 + 1}]")
        if multi:
            gen.body.append("")
            gen.body.append(f"# === Panel {i + 1} ===")
        if panel["plot_type"] == "horizontal_map":
            gen.map_panel(panel, datasets)
        elif panel["plot_type"] == "section_2d":
            gen.section_panel(panel, datasets)
        elif panel["plot_type"] == "line_1d":
            gen.line_panel(panel, datasets)
        elif panel["plot_type"] == "scatter_2d":
            gen.scatter_panel(panel, datasets)
        elif panel["plot_type"] == "heatmap":
            gen.heatmap_panel(panel, datasets)
        elif panel["plot_type"] == "dist_1d":
            gen.dist_panel(panel, datasets)
        elif panel["plot_type"] == "agg_2d":
            gen.agg_panel(panel, datasets)
        else:
            raise NotImplementedError(f"Unsupported plot_type: {panel['plot_type']}")
        if collect_axes:
            gen.body.append("axes.append(ax)")
    _emit_shared_colorbar(gen, shared_cbar)


def _emit_shared_colorbar(gen: "_ScriptBuilder", shared_cbar: dict) -> None:
    """全パネル共通カラーバーのコードを emit する (render._draw_shared_colorbar と1対1)。

    fill レイヤーが1つも無ければ render 側と同様に何もしない。
    """
    if not shared_cbar.get("show") or gen.first_fill_var is None:
        return
    gen.body.append("")
    gen.body.append("# Colorbar shared by all panels")
    gen.body.append(f"scbar = fig.colorbar({gen.first_fill_var}, ax=axes, "
                    + _fmt_kwargs_inline(colorbar_kwargs(shared_cbar)) + ")")
    plan = colorbar_side_plan(shared_cbar)
    if plan:
        gen.body.append(f"scbar.ax.{plan[0]}.set_ticks_position({plan[1]!r})")
        gen.body.append(f"scbar.ax.{plan[0]}.set_label_position({plan[2]!r})")
    if shared_cbar.get("label"):
        label_kw = colorbar_label_kwargs(shared_cbar)
        if label_kw:
            gen.body.append(f"scbar.set_label({shared_cbar['label']!r}, "
                            + _fmt_kwargs_inline(label_kw) + ")")
        else:
            gen.body.append(f"scbar.set_label({shared_cbar['label']!r})")
    if shared_cbar.get("tick_fontsize"):
        gen.body.append(f"scbar.ax.tick_params(labelsize={shared_cbar['tick_fontsize']!r})")
    if shared_cbar.get("outline_width") is not None:
        gen.body.append(
            f"scbar.outline.set_linewidth({float(shared_cbar['outline_width'])!r})")
    if shared_cbar.get("tick_width") is not None:
        gen.body.append(
            f"scbar.ax.tick_params(width={float(shared_cbar['tick_width'])!r})")
    if shared_cbar.get("tick_pad") is not None:
        gen.body.append(
            f"scbar.ax.tick_params(pad={float(shared_cbar['tick_pad'])!r})")


def _open_dataset_lines(dataset_paths: dict[str, str],
                         dataset_renames: dict[str, dict[str, str]] | None,
                         datasets: dict | None = None) -> list[str]:
    """各 dataset の `xr.open_dataset` 行を組む。rename 指定があれば `.rename(...)` を付与。

    open 行には dataset.open_dataset と同じ decode_timedelta=False を付ける
    (timedelta64 デコードの無効化。1対1対応)。
    cftime 暦を読み込み時に変換した dataset (attrs の CALENDAR_CONVERTED_ATTR
    で判定) には、同じ変換行を rename より前に出す (dataset.open_dataset の
    変換と1対1対応)。方式は datetime64 (convert_calendar) / daynum
    (固定長暦 → 開始年からの通し日数) / elapsed (datetime64[ns] 範囲外の
    日付 → 先頭時刻からの経過日数) の3種。
    座標ファイルを結び付けた dataset (attrs の COORD_FILES_ATTR) には、座標ファイルの
    open 行と assign_coords 行を rename より前に出す (dataset.attach_coord_files と
    1対1対応。値は位置ベースで付ける)。座標ファイルのパスは本体のパスが相対なら相対に
    揃える (アプリの「netCDF パスの形式」)。
    """
    renames = dataset_renames or {}
    lines = []
    for dsid, path in dataset_paths.items():
        lines.append(f"{dsid} = xr.open_dataset({path!r}, decode_timedelta=False)")
        ds = (datasets or {}).get(dsid)
        marker = ds.attrs.get(CALENDAR_CONVERTED_ATTR) if ds is not None else None
        if marker:
            parts = str(marker).split(":")
            dim, calendar = parts[0], parts[1]
            mode = parts[2] if len(parts) > 2 else "datetime64"
            if mode == "datetime64":
                lines.append(f"{dsid} = {dsid}.convert_calendar("
                             f"'proleptic_gregorian', dim={dim!r}, "
                             f"use_cftime=False)")
            elif mode == "elapsed":
                # datetime64[ns] 範囲外の日付。先頭時刻からの経過日数へ
                # (dataset._convert_cftime_calendar のフォールバックと同じ式)
                tvar = f"_t_{dsid}"
                lines.append(f"{tvar} = {dsid}[{dim!r}].values")
                lines.append(f"_t0_{dsid} = {tvar}[0]")
                lines.append(f"{dsid} = {dsid}.assign_coords({{{dim!r}: [")
                lines.append("    d.days + d.seconds / 86400")
                lines.append(f"    for d in (t - _t0_{dsid} for t in {tvar})]}})")
                # 軸ラベルを揃えるため、変換済み dataset の属性値をそのまま写す
                attrs = {"units": ds[dim].attrs.get("units", "day"),
                         "long_name": ds[dim].attrs.get("long_name", "")}
                lines.append(f"{dsid}[{dim!r}].attrs.update({attrs!r})")
            else:  # daynum: dataset._convert_cftime_calendar と同じ式
                length = {"360_day": 360.0, "all_leap": 366.0,
                          "366_day": 366.0}[calendar]
                tvar = f"_t_{dsid}"
                lines.append(f"{tvar} = {dsid}[{dim!r}].values")
                lines.append(f"_y0_{dsid} = int({tvar}[0].year)")
                lines.append(f"{dsid} = {dsid}.assign_coords({{{dim!r}: [")
                lines.append(f"    (t.year - _y0_{dsid}) * {length!r} + t.dayofyr")
                lines.append("    + t.hour / 24 + t.minute / 1440 + t.second / 86400")
                lines.append(f"    for t in {tvar}]}})")
                lines.append(f"{dsid}[{dim!r}].attrs.update("
                             f"{{'units': 'day', 'long_name': "
                             f"'time (day number, {calendar} calendar)'}})")
        coord_marker = ds.attrs.get(COORD_FILES_ATTR) if ds is not None else None
        if coord_marker:
            relative = not os.path.isabs(str(path))
            opened: dict[str, str] = {}
            assigns = []
            for cpath, cvar in json.loads(coord_marker):
                if cpath not in opened:
                    cname = f"_c{len(opened)}_{dsid}"
                    opened[cpath] = cname
                    out_path = os.path.relpath(cpath) if relative else cpath
                    lines.append(f"{cname} = xr.open_dataset({out_path!r}, "
                                 f"decode_timedelta=False)")
                cname = opened[cpath]
                assigns.append(f"{cvar!r}: ({cname}[{cvar!r}].dims, "
                               f"{cname}[{cvar!r}].values, {cname}[{cvar!r}].attrs)")
            lines.append(f"{dsid} = {dsid}.assign_coords({{{', '.join(assigns)}}})")
        rn = renames.get(dsid)
        if rn:
            lines.append(f"{dsid} = {dsid}.rename({rn!r})")
    return lines


def generate_animation_script(figure_config: dict, datasets: dict[str, xr.Dataset],
                               dataset_paths: dict[str, str], *,
                               time_values: list | None = None,
                               centers: list | None = None,
                               frames_per_time: int = 1,
                               output_path: str = "animation.gif",
                               fps: int = 4, frame_dpi: int = 100,
                               format: str = "gif",
                               dataset_renames: dict[str, dict[str, str]] | None = None) -> str:
    """アニメーション (GIF または MP4) を生成する再現スクリプトを返す。

    フレームのループを回し、フレームを結合してファイルとして書き出す。
    - time_values: 各フレームの時刻 (時刻送り)。None なら時刻はパネルの selection のまま
    - centers: 各フレームの投影中心 (lon, lat) (Orthographic の地球回転、
      render.rotation_path)。None なら投影はそのまま
    - frames_per_time: 各時刻を何コマ保持するか (render.expand_time_values と同じ
      内包表記をスクリプトに書く)
    両方渡すと時刻 (展開後) と中心が同じ長さで同時に動く (render.iter_frames と1対1)。
    - format="gif": Pillow でフレーム結合 (render.save_animation_gif と完全一致。
      回転時は固定サイズ = animation_gif_tight)
    - format="mp4": tempdir に PNG を書き出して ffmpeg subprocess で結合
      (render.save_animation_mp4 と完全一致)
    """
    if format not in ("gif", "mp4"):
        raise ValueError(f"Unsupported format: {format}")
    if time_values is None and centers is None:
        raise ValueError("generate_animation_script: time_values or centers is required")
    frames_per_time = int(frames_per_time)
    if frames_per_time < 1:
        raise ValueError("generate_animation_script: frames_per_time must be >= 1")
    if (time_values is not None and centers is not None
            and len(time_values) * frames_per_time != len(centers)):
        raise ValueError("generate_animation_script: time_values (x frames_per_time) "
                         "and centers must have the same length")
    # 時刻次元を判定 (最初のレイヤーを持つパネルから。dim 名整列済みのため全パネル共通)。
    # 全パネルの .sel(time=...) が同じ time_value 変数で書かれ、時刻が同期して送られる
    time_dim = None
    if time_values is not None:
        for panel in figure_config["panels"]:
            if panel.get("layers"):
                ds0 = datasets[panel["layers"][0]["dataset_id"]]
                time_dim = detect_coord_roles(ds0).get("time")
                break
        if time_dim is None:
            raise RenderError("no_time_dim_script")

    # render.iter_frames と同じルールで selection[time_dim] を確保する。
    # 生成される .sel は _sel_arg が time_value 変数に置き換えるが、生成時の
    # データ評価 (自動レベル計算等) にも使われるため実在する時刻値を入れる
    figure_config = copy.deepcopy(figure_config)
    if time_dim is not None:
        for panel in figure_config["panels"]:
            if panel_animates_time(panel, time_dim):
                panel.setdefault("selection", {}).setdefault(time_dim, time_values[0])
                # レイヤー側で時刻を固定している設定も render.iter_frames と同じく
                # 先頭の時刻に揃える (生成時のデータ評価用。.sel 自体は _sel_arg が
                # time_value 変数に置き換える)
                for layer in panel.get("layers") or []:
                    layer_sel = layer.get("selection")
                    if layer_sel and time_dim in layer_sel:
                        layer_sel[time_dim] = time_values[0]

    center_vars = ("center_lon", "center_lat") if centers is not None else None
    gen = _ScriptBuilder(animation_time_dim=time_dim, animation_time_var="time_value",
                         animation_center_vars=center_vars)
    _emit_figure_lines(gen, figure_config)
    _emit_panels(gen, figure_config, datasets)

    # 描画ボディをフレームのループでラップ。ループ変数は動かすものに応じて
    # time_value / (center_lon, center_lat) / その両方 (zip)
    frame_body = gen.body
    frame_lists = []
    if time_values is not None:
        frame_lists.append(f"time_values = {list(time_values)!r}")
        if frames_per_time > 1:
            # render.expand_time_values と同じ展開 (各時刻を k コマ保持)
            frame_lists.append(
                f"time_values = [t for t in time_values for _ in range({frames_per_time})]"
                f"  # {frames_per_time} frames per time step")
    if centers is not None:
        frame_lists.append(
            f"centers = {[(float(a), float(b)) for a, b in centers]!r}")
    if time_values is not None and centers is not None:
        loop_target = "time_value, (center_lon, center_lat)"
        loop_iter = "zip(time_values, centers)"
    elif centers is not None:
        loop_target = "(center_lon, center_lat)"
        loop_iter = "centers"
    else:
        loop_target = "time_value"
        loop_iter = "time_values"
    if format == "gif":
        looped = frame_lists + [
            "_frames = []",
            f"for {loop_target} in {loop_iter}:",
        ]
        looped += [f"    {line}" if line else "" for line in frame_body]
        if animation_gif_tight(centers):
            save_line = (f"    fig.savefig(_buf, format='png', bbox_inches='tight', "
                         f"dpi={frame_dpi!r})")
        else:
            save_line = f"    fig.savefig(_buf, format='png', dpi={frame_dpi!r})"
        looped += [
            "    _buf = io.BytesIO()",
            save_line,
            "    plt.close(fig)",
            "    _buf.seek(0)",
            "    _frames.append(Image.open(_buf).convert('RGB'))",
            "",
            f"_frames[0].save({output_path!r}, format='GIF', save_all=True,",
            "                append_images=_frames[1:],",
            f"                duration=int(1000 / {fps!r}), loop=0)",
        ]
    else:  # mp4
        # enumerate の入れ子: 複数のループ変数はまとめて括弧で受ける
        # (`for _i, (time_value, (center_lon, center_lat)) in enumerate(zip(...))`)
        mp4_target = f"({loop_target})" if "," in loop_target.split("(")[0] else loop_target
        looped = frame_lists + [
            "_tmp = tempfile.mkdtemp()",
            "try:",
            f"    for _i, {mp4_target} in enumerate({loop_iter}):",
        ]
        looped += [f"        {line}" if line else "" for line in frame_body]
        looped += [
            f"        fig.savefig(os.path.join(_tmp, f'frame_{{_i:05d}}.png'), dpi={frame_dpi!r})",
            "        plt.close(fig)",
            "",
            "    _cmd = [",
            "        'ffmpeg', '-y',",
            f"        '-framerate', {str(fps)!r},",
            "        '-i', os.path.join(_tmp, 'frame_%05d.png'),",
            "        '-c:v', 'libx264',",
            "        '-pix_fmt', 'yuv420p',",
            "        '-vf', 'scale=trunc(iw/2)*2:trunc(ih/2)*2',",
            f"        {output_path!r},",
            "    ]",
            "    subprocess.run(_cmd, check=True)",
            "finally:",
            "    shutil.rmtree(_tmp, ignore_errors=True)",
        ]
    gen.body = looped

    if format == "gif":
        imports_first, imports_last = ["import io"], ["from PIL import Image"]
    else:
        imports_first = ["import os", "import shutil", "import subprocess", "import tempfile"]
        imports_last = []
    return _assemble_script(gen, figure_config, dataset_paths, dataset_renames, datasets,
                            header_kind="Animation reproduction script",
                            imports_first=imports_first, imports_last=imports_last)


def _projection_expr(proj_cfg: dict, center_vars: tuple[str, str] | None = None) -> str:
    """投影オブジェクトの生成式。

    center_vars を渡すと Orthographic の中心経度・緯度をその変数名で書く
    (地球回転アニメーション: render.iter_frames の centers 上書きと1対1)。
    """
    name = proj_cfg.get("name", "PlateCarree")
    clon = proj_cfg.get("central_longitude", 0.0)
    if name == "PlateCarree":
        return f"ccrs.PlateCarree(central_longitude={clon!r})"
    if name in ("Robinson", "EqualEarth"):
        return f"ccrs.{name}(central_longitude={clon!r})"
    if name in ("NorthPolarStereo", "SouthPolarStereo"):
        return f"ccrs.{name}(central_longitude={clon!r})"
    if name == "Orthographic":
        if center_vars:
            return (f"ccrs.Orthographic(central_longitude={center_vars[0]}, "
                    f"central_latitude={center_vars[1]})")
        clat = proj_cfg.get("central_latitude", 0.0)
        return f"ccrs.Orthographic(central_longitude={clon!r}, central_latitude={clat!r})"
    if name == "LambertConformal":
        clat = proj_cfg.get("central_latitude", 39.0)
        sp = tuple(proj_cfg.get("standard_parallels", [33.0, 45.0]))
        return (f"ccrs.LambertConformal(central_longitude={clon!r}, "
                f"central_latitude={clat!r}, standard_parallels={sp!r})")
    raise RenderError("unsupported_projection", name=name)


def _fmt_kwargs_lines(kwargs: dict) -> list[str]:
    return [f"    {k}={v!r}," for k, v in kwargs.items()]


def _fmt_kwargs_inline(kwargs: dict) -> str:
    return ", ".join(f"{k}={v!r}" for k, v in kwargs.items())


def _collect_custom_cmaps(figure_config: dict) -> list[str]:
    """figure_config 内で使われているカスタム cmap 名を順に集める (重複除去)。"""
    used: list[str] = []
    for panel in figure_config.get("panels", []):
        for layer in panel.get("layers", []):
            style = layer.get("style", {})
            cmap = style.get("cmap")
            if (cmap and cmap not in used
                    and custom_cmap_rgb(cmap) is not None):
                used.append(cmap)
    return used


def _custom_cmap_registration_lines(names: list[str]) -> list[str]:
    """カスタムカラーマップを matplotlib に登録するスクリプト行を返す。"""
    if not names:
        return []
    lines = ["# Register custom colormaps (from ~/.climcanvas/cmaps/)"]
    for name in names:
        rgb = custom_cmap_rgb(name) or []
        rgb_str = ", ".join(f"({r!r}, {g!r}, {b!r})" for r, g, b in rgb)
        lines.append(
            f"mpl.colormaps.register("
            f"mcolors.LinearSegmentedColormap.from_list({name!r}, [{rgb_str}]), "
            f"name={name!r}, force=True)")
    lines.append("")
    return lines


def _wrap_hatch_lw(lines: list[str], linewidth: float) -> list[str]:
    """ハッチの contourf 行を plt.rc_context で囲む (linewidth != 1.0 のときのみ)。"""
    if linewidth == 1.0:
        return lines
    return [
        f"with plt.rc_context({{'hatch.linewidth': {linewidth!r}}}):",
        *[f"    {ln}" for ln in lines],
    ]


def _value_transform_line(da_name: str, style: dict) -> str | None:
    """データ値の線形変換行 `da = da * scale + offset` を生成。

    render.apply_value_transform と完全に同じ条件で出力する。デフォルト
    (scale=1.0, offset=0.0) のときは None。
    """
    scale = style.get("value_scale", 1.0)
    offset = style.get("value_offset", 0.0)
    if scale == 1.0 and offset == 0.0:
        return None
    return f"{da_name} = {da_name} * {scale!r} + {offset!r}"


def _maskout_lines(da_name: str, style: dict, mask_name: str | None = None) -> list[str]:
    """maskout の行 `da = da.where(...)` を生成 (GrADS maskout 相当)。

    render.apply_maskout と完全に同じ条件・順序で出力する。below は
    「以下を描かない」(> で残す)、above は「以上を描かない」(< で残す)。
    mask_name (別変数のマスク。_maskout_mask_lines が emit した変数名) が
    あれば var_below / var_above の条件を同じ流儀で続ける。
    値変換行の後に置くこと。未指定 (None) のときは空リスト。
    """
    m = style.get("maskout") or {}
    lines = []
    if m.get("below") is not None:
        lines.append(
            f"{da_name} = {da_name}.where({da_name} > {float(m['below'])!r})")
    if m.get("above") is not None:
        lines.append(
            f"{da_name} = {da_name}.where({da_name} < {float(m['above'])!r})")
    if mask_name is not None:
        if m.get("var_below") is not None:
            lines.append(
                f"{da_name} = {da_name}.where({mask_name} > {float(m['var_below'])!r})")
        if m.get("var_above") is not None:
            lines.append(
                f"{da_name} = {da_name}.where({mask_name} < {float(m['var_above'])!r})")
    return lines


def _contour_neg_linestyle_line(cs_name: str, style: dict) -> str | None:
    """正と負で線種を分けるための後処理行 (描画後の `cs.set_linestyle(...)`)。

    render.apply_contour_linestyles と完全に同じ条件で出力する。
    """
    neg = style.get("negative_linestyle")
    pos = style.get("linestyle", "solid")
    if not neg or neg == pos:
        return None
    return (f"{cs_name}.set_linestyle("
            f"[{neg!r} if lev < 0 else {pos!r} for lev in {cs_name}.levels])")


def _contour_emphasis_lines(cs_name: str, style: dict) -> list[str]:
    """指定レベルの太さ・色を変える後処理行 (render.apply_contour_emphasis と1対1)。"""
    emp = style.get("emphasis") or {}
    targets = emp.get("levels")
    lw = emp.get("linewidth")
    color = emp.get("color")
    if not targets or (lw is None and color is None):
        return []
    targets = [float(v) for v in targets]
    lines = [
        f"_emp_t = {targets!r}",
        f"_emp_is = [any(abs(float(lev) - t) <= 1e-09 for t in _emp_t) "
        f"for lev in {cs_name}.levels]",
    ]
    if lw is not None:
        base_lw = float(style.get("linewidth", 1.0))
        lines.append(
            f"{cs_name}.set_linewidth([{float(lw)!r} if e else {base_lw!r} "
            "for e in _emp_is])")
    if color is not None:
        if style.get("use_cmap"):
            # numpy に依存しないよう list で渡す (to_rgba の結果は同一)
            base = (f"list({cs_name}.to_rgba("
                    f"[float(x) for x in {cs_name}.levels]))")
        else:
            base = f"[{style.get('color', 'black')!r}] * len({cs_name}.levels)"
        lines.append(f"_emp_base = {base}")
        lines.append(
            f"{cs_name}.set_edgecolor([{color!r} if e else _emp_base[i] "
            "for i, e in enumerate(_emp_is)])")
    return lines


def _contour_label_levels_lines(cs_name: str, style: dict) -> tuple[list[str], str]:
    """clabel の levels 引数 (非表示レベルのラベル除外) の行と引数文字列を返す。

    render.contour_label_levels と1対1対応。emphasis の太さ 0 (非表示) が
    無ければ ([], "") — 従来どおり levels 引数なしの clabel になる。
    """
    emp = style.get("emphasis") or {}
    targets = emp.get("levels")
    lw = emp.get("linewidth")
    if not targets or lw is None or float(lw) != 0.0:
        return [], ""
    targets = [float(v) for v in targets]
    lines = [
        f"_lbl_lv = [float(lev) for lev in {cs_name}.levels",
        f"           if not any(abs(float(lev) - t) <= 1e-09 "
        f"for t in {targets!r})]",
    ]
    return lines, "_lbl_lv, "


class _ScriptBuilder:
    def __init__(self, animation_time_dim: str | None = None,
                 animation_time_var: str = "time_value",
                 animation_center_vars: tuple[str, str] | None = None):
        self.body: list[str] = []
        self.needs_numpy = False
        self.needs_mticker = False
        self.needs_mdates = False
        self.needs_mpath = False
        self.needs_ccrs = False
        self.needs_feature = False
        self.needs_pandas = False
        self.needs_mcolors = False
        # アニメーション生成時のみ非 None。指定された次元の .sel は
        # リテラルではなく `animation_time_var` という変数で書く
        self.animation_time_dim = animation_time_dim
        self.animation_time_var = animation_time_var
        # 地球回転アニメーション生成時のみ非 None。Orthographic の投影中心を
        # リテラルではなく (経度変数名, 緯度変数名) で書く (_projection_expr)
        self.animation_center_vars = animation_center_vars
        # 塗りポリゴンの反転ガード (render.drop_inverting_contour_rings) を
        # 使うスクリプトか。True なら関数本体と import を冒頭に出す
        self.needs_inversion_guard = False
        # 第2軸との値揃え (render.align_twin_ylim) を使うスクリプトか。
        # True なら関数本体を冒頭に埋め込む
        self.needs_twin_align = False
        # add_subplot の位置引数。複数パネルでは呼び出し側がパネル毎に設定する
        # add_subplot の位置引数。第3要素はセル番号 (int) または
        # 結合セルの (左上, 右下) タプル (render.parse_mosaic 参照)
        self.subplot: tuple = (1, 1, 1)
        # 行・列の比率指定時の GridSpec 添字テキスト (例 "gs[0, 1]")。
        # 設定されていると _subplot_args はこちらを返す (render の GridSpec
        # 分岐と1対1。呼び出し側が emit_panels でパネル毎に設定する)
        self.subplot_gs: str | None = None
        self._counts: dict[str, int] = {}
        self._map_cbars: list[tuple[str, dict]] = []
        # 共通カラーバー用: 最初の fill レイヤーの mappable 変数名
        self.first_fill_var: str | None = None

    def _name(self, base: str) -> str:
        self._counts[base] = self._counts.get(base, 0) + 1
        n = self._counts[base]
        return base if n == 1 else f"{base}{n}"

    def _subplot_args(self) -> str:
        if self.subplot_gs:
            return self.subplot_gs
        # int は "4"、結合セルのタプルは "(5, 6)" になる (repr がそのまま
        # add_subplot の合法な引数表記。単一セルの出力は従来と同一テキスト)
        r, c, i = self.subplot
        return f"{r}, {c}, {i!r}"

    def _emit_box_aspect(self, panel: dict) -> None:
        """panel.box_aspect が指定されていれば ax.set_box_aspect(value) を emit。"""
        ba = panel.get("box_aspect")
        if ba is not None:
            self.body.append(f"ax.set_box_aspect({float(ba)!r})")

    def _tick_settings_lines(self, axis_cfg: dict, target: str = "ax") -> None:
        """目盛の共通設定 (render._apply_tick_settings と1対1対応)。

        対数軸 (set_xscale/set_yscale) の emit の後に呼ぶこと —
        明示指定した目盛位置を対数の既定目盛より優先するため。
        line_1d の第2軸 (twinx) には secondary_axis_cfg で読み替えた設定を
        target="ax2" で当てる。
        """
        body = self.body
        ax = target
        # 縦軸の左右入れ替え (render._apply_tick_settings と1対1: 非表示設定より前)
        if axis_cfg.get("swap_y_sides"):
            body.append(f"{ax}.yaxis.tick_right()")
            body.append(f"{ax}.yaxis.set_label_position('right')")
        if axis_cfg.get("tick_fontsize"):
            body.append(f"{ax}.tick_params(labelsize={axis_cfg['tick_fontsize']!r})")
        if axis_cfg.get("tick_width") is not None:
            body.append(f"{ax}.tick_params(which='both', "
                        f"width={float(axis_cfg['tick_width'])!r})")
        if not axis_cfg.get("show_x_ticklabels", True):
            body.append(f"{ax}.tick_params(axis='x', labelbottom=False, labeltop=False)")
        if not axis_cfg.get("show_y_ticklabels", True):
            body.append(f"{ax}.tick_params(axis='y', labelleft=False, labelright=False)")
        if axis_cfg.get("x_tick_rotation"):
            body.append(f"{ax}.tick_params(axis='x', "
                        f"labelrotation={float(axis_cfg['x_tick_rotation'])!r})")
        if axis_cfg.get("y_tick_rotation"):
            body.append(f"{ax}.tick_params(axis='y', "
                        f"labelrotation={float(axis_cfg['y_tick_rotation'])!r})")
        xtp = axis_cfg.get("x_tick_positions")
        xti = axis_cfg.get("x_tick_interval")
        if xtp:
            self.needs_mticker = True
            pos = [float(v) for v in xtp]
            body.append(
                f"{ax}.xaxis.set_major_locator(mticker.FixedLocator({pos!r}))")
            xtl = axis_cfg.get("x_tick_labels")
            if xtl and len(xtl) == len(xtp):
                labels = [str(s) for s in xtl]
                body.append(
                    f"{ax}.xaxis.set_major_formatter("
                    f"mticker.FixedFormatter({labels!r}))")
        elif xti is not None:
            self.needs_mticker = True
            loc_expr = ("mticker.NullLocator()" if float(xti) == 0
                         else f"mticker.MultipleLocator({float(xti)!r})")
            body.append(f"{ax}.xaxis.set_major_locator({loc_expr})")
        ytp = axis_cfg.get("y_tick_positions")
        yti = axis_cfg.get("y_tick_interval")
        if ytp:
            self.needs_mticker = True
            pos = [float(v) for v in ytp]
            body.append(
                f"{ax}.yaxis.set_major_locator(mticker.FixedLocator({pos!r}))")
            ytl = axis_cfg.get("y_tick_labels")
            if ytl and len(ytl) == len(ytp):
                labels = [str(s) for s in ytl]
                body.append(
                    f"{ax}.yaxis.set_major_formatter("
                    f"mticker.FixedFormatter({labels!r}))")
        elif yti is not None:
            self.needs_mticker = True
            loc_expr = ("mticker.NullLocator()" if float(yti) == 0
                         else f"mticker.MultipleLocator({float(yti)!r})")
            body.append(f"{ax}.yaxis.set_major_locator({loc_expr})")

    def _secondary_axis_lines(self, axis_cfg: dict, label_base: dict) -> None:
        """第2軸 (twinx) の体裁 (render._style_secondary_axis と1対1・同順)。

        secondary_axis_cfg で y2 設定を y スロットへ読み替え、第1軸と同じ
        emit を target="ax2" で行う。
        """
        body = self.body
        cfg2 = secondary_axis_cfg(axis_cfg)
        grid = cfg2["grid"]
        if grid.get("show_y"):
            body.append(
                f"ax2.grid(axis='y', color={grid.get('color', 'gray')!r}, "
                f"linewidth={grid.get('width', 0.5)!r}, "
                f"linestyle={grid.get('linestyle', ':')!r})")
        if cfg2.get("show_y_minor_ticks"):
            self.needs_mticker = True
            body.append("ax2.yaxis.set_minor_locator(mticker.AutoMinorLocator())")
        if cfg2.get("y_label"):
            kw = dict(label_base)
            if cfg2.get("y_label_rotation") is not None:
                kw["rotation"] = float(cfg2["y_label_rotation"])
            args = ", ".join([repr(cfg2["y_label"])]
                              + [f"{k}={v!r}" for k, v in kw.items()])
            body.append(f"ax2.set_ylabel({args})")
        if cfg2.get("log_y"):
            self.needs_mticker = True
            body.append("ax2.set_yscale('log')")
            body.append("ax2.yaxis.set_major_formatter(mticker.ScalarFormatter())")
            body.append("ax2.yaxis.set_minor_formatter(mticker.NullFormatter())")
        # 縦軸の左右入れ替え: 第2軸 → 左 (第1軸 → 右は _tick_settings_lines)
        if axis_cfg.get("swap_y_sides"):
            body.append("ax2.yaxis.tick_left()")
            body.append("ax2.yaxis.set_label_position('left')")
        self._tick_settings_lines(cfg2, "ax2")
        if cfg2.get("tight_y") and not cfg2.get("y_lim"):
            body.append("ax2.autoscale(axis='y', tight=True)")
        if cfg2.get("invert_y"):
            body.append("ax2.invert_yaxis()")
        if cfg2.get("y_lim"):
            body.append(f"ax2.set_ylim({tuple(cfg2['y_lim'])!r})")

    def _frame_lines(self, panel: dict, target: str = "ax") -> None:
        """axes 枠線 (spine) の行を emit する (render._apply_frame と1対1対応)。

        dist_1d の第2軸 (twinx) には target="ax2" で同じ設定を当てる。
        """
        body = self.body
        frame = panel.get("frame") or {}
        for side in ("top", "bottom", "left", "right"):
            if not frame.get(f"show_{side}", True):
                body.append(f"{target}.spines[{side!r}].set_visible(False)")
        if frame.get("width") is not None:
            body.append(f"for _spine in {target}.spines.values(): "
                        f"_spine.set_linewidth({float(frame['width'])!r})")
        if frame.get("color"):
            body.append(f"for _spine in {target}.spines.values(): "
                        f"_spine.set_color({frame['color']!r})")

    def _frame_background_lines(self, panel: dict) -> None:
        """axes 枠線 (spine) と背景色 (render._apply_frame_background と1対1対応)。"""
        body = self.body
        self._frame_lines(panel, "ax")
        background = panel.get("background") or {}
        if background.get("color"):
            body.append(f"ax.set_facecolor({background['color']!r})")
        # 範囲を指定した塗り (axvspan / axhspan)。zorder=0 で背面、
        # linewidth=0 で縁取りなし (render._apply_frame_background と同じ)
        for span in background.get("spans") or []:
            fn = "axvspan" if span.get("orientation", "x") == "x" else "axhspan"
            exprs = []
            for v in (span["lo"], span["hi"]):
                if isinstance(v, str):  # 時間軸: ISO 文字列 → datetime64
                    self.needs_numpy = True
                    exprs.append(f"np.datetime64({v!r})")
                else:
                    exprs.append(repr(float(v)))
            body.append(
                f"ax.{fn}({exprs[0]}, {exprs[1]}, "
                f"color={span.get('color', '#ffd7d7')!r}, "
                f"alpha={float(span.get('alpha', 0.3))!r}, "
                f"linewidth=0, zorder=0)")
        # 基準線 (axvline / axhline) + 端の文字 (render._draw_refline と1対1)
        for refline in background.get("reflines") or []:
            v = refline.get("value", 0.0)
            if isinstance(v, str):  # 時間軸: ISO 文字列 → datetime64
                self.needs_numpy = True
                v_expr = f"np.datetime64({v!r})"
            else:
                v_expr = repr(float(v))
            vertical = refline.get("orientation", "y") == "x"
            body.append(f"ax.{'axvline' if vertical else 'axhline'}({v_expr}, "
                        + _fmt_kwargs_inline(refline_kwargs(refline)) + ")")
            if refline.get("text"):
                tkw = _fmt_kwargs_inline(refline_text_kwargs(refline))
                if vertical:
                    body.append(
                        f"ax.text({v_expr}, 0.98, {refline['text']!r}, "
                        f"transform=ax.get_xaxis_transform(), rotation=90, "
                        f"ha='right', va='top', {tkw})")
                else:
                    body.append(
                        f"ax.text(0.98, {v_expr}, {refline['text']!r}, "
                        f"transform=ax.get_yaxis_transform(), "
                        f"ha='right', va='bottom', {tkw})")

    # --- 水平断面図 (horizontal_map) ---

    def map_panel(self, panel: dict, datasets: dict):
        body = self.body
        self.needs_ccrs = True
        body.append(f"ax = fig.add_subplot({self._subplot_args()}, "
                    f"projection={_projection_expr(panel['projection'], self.animation_center_vars)})")
        self._emit_box_aspect(panel)
        body.append("")

        map_cfg = panel.get("map", {})
        ne_scale = natural_earth_scale(map_cfg)
        land_fg = land_foreground(map_cfg)

        def _ne_feature(name: str) -> str:
            # render の _ne_feature と 1対1 (None = 自動は組み込み feature のまま)
            return (f"cfeature.{name}" if ne_scale is None
                    else f"cfeature.{name}.with_scale({ne_scale!r})")

        land = map_cfg.get("land", {})
        if land.get("show"):
            self.needs_feature = True
            body.append(f"ax.add_feature({_ne_feature('LAND')}, "
                        f"facecolor={land.get('color', '#d9d2c2')!r}, "
                        f"zorder={(LAND_FG_ZORDER if land_fg else 0)!r})")
        ocean = map_cfg.get("ocean", {})
        if ocean.get("show"):
            self.needs_feature = True
            body.append(f"ax.add_feature({_ne_feature('OCEAN')}, "
                        f"facecolor={ocean.get('color', '#cfe2f3')!r}, zorder=0)")
        if land.get("show") or ocean.get("show"):
            body.append("")

        # 表示範囲 (extent / 円形・扇形境界) は render と同じく**レイヤーより前**に
        # 確定させる (streamplot が呼び出し時点の表示範囲でサンプルするため)
        region = panel.get("region")
        proj_name = panel["projection"].get("name", "PlateCarree")
        sector_mode = bool(use_circular_boundary(panel["projection"]) and region
                           and not region_spans_all_longitudes(region))
        extent = None
        if region and not sector_mode and proj_name != "Orthographic":
            extent, clon = extent_args(region, panel["projection"])
            if extent_is_global(extent):
                extent = None
        cv_id = (curvilinear_extent_dataset(panel, datasets)
                 if extent is None and not sector_mode else None)
        if extent is not None:
            body.append(f"ax.set_extent({extent!r}, "
                        f"crs=ccrs.PlateCarree(central_longitude={clon!r}))")
        elif cv_id is not None:
            # 2 次元座標格子で領域未指定: 全格子点の投影座標の範囲 (render.curvilinear_extent
            # と同じ計算。投影できない点は除く)
            self.needs_numpy = True
            cv_roles = detect_coord_roles(datasets[cv_id])
            body += [
                f"_pts = ax.projection.transform_points(ccrs.PlateCarree(), "
                f"{cv_id}[{cv_roles['lon']!r}].values.astype(float), "
                f"{cv_id}[{cv_roles['lat']!r}].values.astype(float))",
                "_px, _py = _pts[..., 0], _pts[..., 1]",
                "_ok = np.isfinite(_px) & np.isfinite(_py)",
                "ax.set_xlim(float(_px[_ok].min()), float(_px[_ok].max()))",
                "ax.set_ylim(float(_py[_ok].min()), float(_py[_ok].max()))",
            ]
        elif not sector_mode:
            # 領域未指定 = 全球表示 (render 側と同一条件)。maskout や欠損で
            # 端の緯度帯が塗られなくても地図が縮まないようにする
            body.append("ax.set_global()")

        if use_circular_boundary(panel["projection"]):
            if sector_mode:
                # render.sector_boundary_path() と同じ構成の扇形パス
                self.needs_mpath = True
                body.append(f"sector = mpath.Path({sector_vertices(region)!r})"
                            ".interpolated(50).vertices")
                body.append("sector_xy = ax.projection.transform_points("
                            "ccrs.PlateCarree(), sector[:, 0], sector[:, 1])[:, :2]")
                body.append("ax.set_boundary(mpath.Path(sector_xy))")
                body.append("ax.set_xlim(sector_xy[:, 0].min(), sector_xy[:, 0].max())")
                body.append("ax.set_ylim(sector_xy[:, 1].min(), sector_xy[:, 1].max())")
            else:
                # render.circular_boundary_path() と同じ構成の円パス
                self.needs_numpy = True
                self.needs_mpath = True
                body.append("theta = np.linspace(0.0, 2.0 * np.pi, 100)")
                body.append("circle = mpath.Path(np.vstack([np.sin(theta), np.cos(theta)]).T"
                            " * 0.5 + [0.5, 0.5])")
                body.append("ax.set_boundary(circle, transform=ax.transAxes)")
        body.append("")

        for layer in panel["layers"]:
            kind = layer["kind"]
            if kind == "fill":
                self.fill_layer(panel, layer, datasets)
            elif kind == "hatch":
                self.hatch_layer(panel, layer, datasets)
            elif kind == "contour":
                self.contour_layer(panel, layer, datasets)
            elif kind == "vector":
                self.vector_layer(panel, layer, datasets)
            elif kind == "stream":
                self.stream_layer(panel, layer, datasets)
            elif kind == "map_scatter":
                self.map_scatter_layer(panel, layer, datasets)
            elif kind == "track":
                self.track_layer(panel, layer, datasets)
            else:
                raise NotImplementedError(f"Unsupported layer kind: {kind}")

        coast = map_cfg.get("coastlines", {})
        if map_cfg.get("borders"):
            self.needs_feature = True
            body.append(f"ax.add_feature({_ne_feature('BORDERS')}, "
                        f"linewidth={coast.get('width', 0.8)!r}, "
                        f"edgecolor={coast.get('color', 'black')!r})")
        if coast.get("show", True):
            # 自動 (None) のときは resolution を省略して cartopy 既定 ('auto') に任せる
            res_arg = "" if ne_scale is None else f"resolution={ne_scale!r}, "
            body.append(f"ax.coastlines({res_arg}linewidth={coast.get('width', 0.8)!r}, "
                        f"color={coast.get('color', 'black')!r})")

        gl_cfg = map_cfg.get("gridlines", {})
        if gl_cfg.get("show", True):
            plan = gridline_plan(gl_cfg)
            sides = gl_cfg.get("label_sides", {}) if plan["labels"] else {}
            # geo / inline は gl.geo_labels / gl.inline_labels に対応 (render と1対1)
            hidden_sides = [s for s in ("left", "right", "top", "bottom",
                                        "geo", "inline")
                            if not sides.get(s, True)]
            x_style, y_style = gridline_label_styles(gl_cfg)
            label_filters = gridline_label_filters(
                gl_cfg, panel["projection"], panel.get("region"))
            label_extras = bool(plan["labels"] and (
                x_style or y_style or hidden_sides or label_filters
                or gl_cfg.get("label_padding") is not None))
            emitted_gl = False
            # 線用の Gridliner (split 時はラベルを持たない。render と1対1対応)
            if plan["lines"]:
                draw = plan["labels"] and not plan["split"]
                needs_gl = bool(plan["line_lon"] or plan["line_lat"]
                                or (draw and label_extras))
                prefix = "gl = " if needs_gl else ""
                body.append(prefix + "ax.gridlines("
                            + _fmt_kwargs_inline(gridline_kwargs(
                                gl_cfg, panel["projection"], draw_labels=draw))
                            + ")")
                emitted_gl = needs_gl
                if plan["line_lon"]:
                    self.needs_mticker = True
                    body.append(f"gl.xlocator = mticker.MultipleLocator({plan['line_lon']!r})")
                if plan["line_lat"]:
                    self.needs_mticker = True
                    body.append(f"gl.ylocator = mticker.MultipleLocator({plan['line_lat']!r})")
            # ラベル用の Gridliner (線が非表示のとき、または間隔が線と異なるとき)
            if plan["labels"] and (plan["split"] or not plan["lines"]):
                body.append("gl = ax.gridlines("
                            + _fmt_kwargs_inline(gridline_kwargs(
                                gl_cfg, panel["projection"], draw_labels=True))
                            + ")")
                body.append("gl.xlines = False")
                body.append("gl.ylines = False")
                emitted_gl = True
                # 開始値 (位相) は offset= (render と1対1。未指定時は従来と同じ出力)
                if plan["label_lon"]:
                    self.needs_mticker = True
                    off = (f", offset={plan['label_lon_start']!r}"
                           if plan["label_lon_start"] is not None else "")
                    body.append(f"gl.xlocator = mticker.MultipleLocator({plan['label_lon']!r}{off})")
                if plan["label_lat"]:
                    self.needs_mticker = True
                    off = (f", offset={plan['label_lat_start']!r}"
                           if plan["label_lat_start"] is not None else "")
                    body.append(f"gl.ylocator = mticker.MultipleLocator({plan['label_lat']!r}{off})")
            # ラベルの体裁 (直前の gl がラベルを持つ Gridliner)
            if plan["labels"] and emitted_gl:
                for side in hidden_sides:
                    body.append(f"gl.{side}_labels = False")
                if x_style:
                    body.append(f"gl.xlabel_style = {x_style!r}")
                if y_style:
                    body.append(f"gl.ylabel_style = {y_style!r}")
                if gl_cfg.get("label_padding") is not None:
                    body.append(f"gl.xpadding = {gl_cfg['label_padding']!r}")
                    body.append(f"gl.ypadding = {gl_cfg['label_padding']!r}")
                if label_filters:
                    # render.apply_gridline_label_filters と1対1。gl/ax は複数
                    # パネルで再代入されるため、既定引数で現在の値を束縛する
                    # (遅延束縛の罠)。フィルタは構成に応じた行だけ emit する
                    keep_lon = label_filters.get("lat_edge_keep_lon")
                    other_lon = label_filters.get("lat_edge_other_lon")
                    geo_hidden = label_filters.get("geo_hidden_sides")
                    lines = [
                        "def _gl_draw_label_filter(renderer=None, gl=gl, ax=ax):",
                        "    # Apply position-based label filters between position calc and drawing",
                        "    gl._draw_gridliner(renderer=renderer)",
                    ]
                    if label_filters.get("hide_pole") or geo_hidden:
                        lines.extend([
                            "    _x0, _x1 = ax.get_xlim()",
                            "    _y0, _y1 = ax.get_ylim()",
                        ])
                    if label_filters.get("hide_pole"):
                        lines.append(
                            "    _tol = 0.05 * max(_x1 - _x0, _y1 - _y0)")
                    if geo_hidden:
                        lines.extend([
                            "    _xmid = 0.5 * (_x0 + _x1)",
                            "    _ymid = 0.5 * (_y0 + _y1)",
                        ])
                    lines.extend([
                        "    for _lb in gl._labels:",
                        "        _lx, _ly = _lb.artist.get_position()",
                    ])
                    if label_filters.get("hide_pole"):
                        lines.extend([
                            "        if _lb.xy == 'x' and abs(_lx) < _tol and abs(_ly) < _tol:",
                            "            _lb.artist.set_visible(False)",  # 極の経度ラベル
                        ])
                    if keep_lon is not None:
                        lines.extend([
                            "        if _lb.xy == 'y':",
                            "            # Classify by sector edge (longitude); hide labels on the other edge",
                            "            _plon = ccrs.PlateCarree().transform_point(_lx, _ly, ax.projection)[0]",
                            f"            _d_keep = abs((_plon - {keep_lon!r} + 180.0) % 360.0 - 180.0)",
                            f"            _d_other = abs((_plon - {other_lon!r} + 180.0) % 360.0 - 180.0)",
                            "            if _d_keep > _d_other:",
                            "                _lb.artist.set_visible(False)",
                        ])
                    if geo_hidden:
                        lines.extend([
                            "        if _lb.loc == 'geo':",
                            "            # Attribute geo-classified labels away from sides to the nearest side",
                            "            if _lb.xy == 'y':",
                            "                _side = 'left' if _lx < _xmid else 'right'",
                            "            else:",
                            "                _side = 'bottom' if _ly < _ymid else 'top'",
                            f"            if _side in {tuple(geo_hidden)!r}:",
                            "                _lb.artist.set_visible(False)",
                        ])
                    lines.extend([
                        "    for _c in gl.get_visible_children():",
                        "        _c.draw(renderer=renderer)",
                        "gl.draw = _gl_draw_label_filter",
                    ])
                    body.extend(lines)

        ticks_cfg = map_cfg.get("ticks", {})
        if ticks_cfg.get("show") and panel["projection"].get("name") == "PlateCarree":
            self.needs_numpy = True
            clon = panel["projection"].get("central_longitude", 0.0)
            lon_int = ticks_cfg.get("lon_interval", 30.0)
            lat_int = ticks_cfg.get("lat_interval", 15.0)
            body.append(f"_lon_start = np.ceil(({clon!r} - 180.0) / {lon_int!r}) * {lon_int!r}")
            body.append(f"_geo_lons = np.arange(_lon_start, {clon!r} + 180.0, {lon_int!r})")
            # Axis.set_ticks は view interval を ticks が収まる範囲へ広げるため、
            # 設定前の表示範囲を保存して最後に復元する (render と1対1)
            body.append("# set_ticks expands the view limits; restore them afterwards")
            body.append("_xlim, _ylim = ax.get_xlim(), ax.get_ylim()")
            body.append(f"ax.set_xticks(((_geo_lons - {clon!r} + 180.0) % 360.0) - 180.0)")
            body.append(f"ax.set_yticks(np.arange(np.ceil(-90.0 / {lat_int!r}) * {lat_int!r}, "
                        f"90.0, {lat_int!r}))")
            body.append("ax.set_xticklabels([])")
            body.append("ax.set_yticklabels([])")
            sides = ticks_cfg.get("sides", {})
            body.append(f"ax.tick_params(length={ticks_cfg.get('length', 4.0)!r}, "
                        f"width={ticks_cfg.get('width', 0.8)!r}, "
                        f"direction={ticks_cfg.get('direction', 'out')!r}, "
                        f"left={sides.get('left', True)!r}, "
                        f"right={sides.get('right', False)!r}, "
                        f"top={sides.get('top', False)!r}, "
                        f"bottom={sides.get('bottom', True)!r})")
            # 短いティック (補助目盛)。render の minor ブロックと1対1対応
            minor_cfg = ticks_cfg.get("minor") or {}
            if minor_cfg.get("show"):
                m_lon = minor_cfg.get("lon_interval", 10.0)
                m_lat = minor_cfg.get("lat_interval", 5.0)
                body.append(f"_lon_start = np.ceil(({clon!r} - 180.0) / {m_lon!r}) * {m_lon!r}")
                body.append(f"_geo_lons = np.arange(_lon_start, {clon!r} + 180.0, {m_lon!r})")
                body.append(f"ax.set_xticks(((_geo_lons - {clon!r} + 180.0) % 360.0) - 180.0, "
                            "minor=True)")
                body.append(f"ax.set_yticks(np.arange(np.ceil(-90.0 / {m_lat!r}) * {m_lat!r}, "
                            f"90.0, {m_lat!r}), minor=True)")
                body.append(f"ax.tick_params(which='minor', "
                            f"length={minor_cfg.get('length', 2.5)!r}, "
                            f"width={minor_cfg.get('width', 0.8)!r}, "
                            f"direction={ticks_cfg.get('direction', 'out')!r}, "
                            f"left={sides.get('left', True)!r}, "
                            f"right={sides.get('right', False)!r}, "
                            f"top={sides.get('top', False)!r}, "
                            f"bottom={sides.get('bottom', True)!r})")
            body.append("ax.set_xlim(_xlim)")
            body.append("ax.set_ylim(_ylim)")

        for box in map_cfg.get("boxes", []) or []:
            self.needs_numpy = True
            lon_min = float(box["lon_min"])
            lon_max = float(box["lon_max"])
            if lon_max < lon_min:
                lon_max += 360.0
            lat_min = float(box["lat_min"])
            lat_max = float(box["lat_max"])
            body += [
                f"_lons = np.concatenate([np.linspace({lon_min!r}, {lon_max!r}, 50), "
                f"np.full(50, {lon_max!r}), np.linspace({lon_max!r}, {lon_min!r}, 50), "
                f"np.full(50, {lon_min!r})])",
                f"_lats = np.concatenate([np.full(50, {lat_min!r}), "
                f"np.linspace({lat_min!r}, {lat_max!r}, 50), np.full(50, {lat_max!r}), "
                f"np.linspace({lat_max!r}, {lat_min!r}, 50)])",
                f"ax.plot(_lons, _lats, color={box.get('color', 'red')!r}, "
                f"linewidth={box.get('linewidth', 1.5)!r}, "
                f"linestyle={box.get('linestyle', 'solid')!r}, "
                f"transform=ccrs.PlateCarree())",
            ]

        if map_cfg.get("frame_width") is not None:
            body.append(f"ax.spines['geo'].set_linewidth({float(map_cfg['frame_width'])!r})")

        self._finish_panel_lines(panel)
        self._match_colorbar_lines()

    def _data_lines(self, name: str, panel: dict, layer: dict, variable: str,
                    datasets: dict, cyclic: bool = False,
                    dataset_id: str | None = None) -> dict:
        """選択・領域切り出し・transpose のコードを body に追加し、座標役割を返す。

        dataset_id で参照先 dataset を上書きできる (ベクトルの y 成分が別ファイル
        のとき。既定 = layer["dataset_id"]。render._layer_data と1対1対応)。
        """
        dsid = dataset_id or layer["dataset_id"]
        ds = datasets[dsid]
        roles = detect_coord_roles(ds)
        lon_name = roles["lon"]

        # panel.selection (時刻) と layer.selection (鉛直レベル等) をマージ。
        # 同じ dim を両方が指定したら layer 側が優先。
        merged_selection = {**(panel.get("selection") or {}),
                            **(layer.get("selection") or {})}
        sel = {dim: val for dim, val in merged_selection.items()
               if dim in ds[variable].dims}
        expr = f"{dsid}[{variable!r}]"
        if sel:
            expr += ".sel(" + ", ".join(self._sel_arg(d, v) for d, v in sel.items()) + ")"
        self.body.append(f"{name} = {expr}")

        region = panel.get("region")
        if region:
            if is_curvilinear(ds, roles):
                # render.select_panel_data と同じ整数 slice を isel で出す
                indexers = curvilinear_region_indexers(ds, region, roles)
                args = ", ".join(f"{dim}=slice({sl.start!r}, {sl.stop!r})"
                                 for dim, sl in indexers.items())
                self.body.append(f"{name} = {name}.isel({args})")
            else:
                indexers = region_indexers(ds, region, roles)
                args = ", ".join(f"{dim}=slice({sl.start!r}, {sl.stop!r})"
                                 for dim, sl in indexers.items())
                self.body.append(f"{name} = {name}.sel({args})")
        # 1 次元格子では (lat, lon)、curvilinear では lat 座標の dims (y, x)
        ydim, xdim = horizontal_dims(ds, roles)
        self.body.append(f"{name} = {name}.transpose({ydim!r}, {xdim!r})")
        if is_curvilinear(ds, roles):
            # 経度の継ぎ目をほどく (render.unwrap_lon2d と同じ計算)
            self.needs_numpy = True
            lon_name = roles["lon"]
            self.body += [
                f"_lonu = np.unwrap({name}[{lon_name!r}].values.astype(float), "
                f"axis=1, period=360.0)",
                "_lonu = _lonu + (np.unwrap(_lonu[:, 0], period=360.0) - _lonu[:, 0])[:, None]",
                f"{name} = {name}.assign_coords({{{lon_name!r}: ({name}[{lon_name!r}].dims, "
                f"_lonu, dict({name}[{lon_name!r}].attrs))}})",
            ]

        if cyclic:
            # render.add_cyclic_lon() と同じ操作。経度0/360°の継ぎ目を閉じる。
            da = select_panel_data(ds, variable, merged_selection, region, roles)
            if needs_cyclic_lon(da, lon_name):
                self.body.append(
                    f"{name} = xr.concat([{name}, {name}.isel({lon_name}=0)"
                    f".assign_coords({lon_name}={name}[{lon_name!r}][0] + 360.0)], "
                    f"dim={lon_name!r})")
        return roles

    def _maskout_mask_lines(self, panel: dict, layer: dict, datasets: dict,
                            style: dict, section: bool) -> str | None:
        """maskout の「別変数」の切り出し行を emit し、変数名を返す (未設定なら None)。

        render._maskout_mask_data と1対1対応: マスク変数を描画変数と同じ
        選択経路 (水平面図は _data_lines / 断面図は _section_data_lines) で
        切り出す。返り値を _maskout_lines の mask_name に渡すこと。
        """
        cfg = maskout_var_config(style)
        if cfg is None:
            return None
        mask = self._name("da_mask")
        if section:
            self._section_data_lines(mask, panel, layer, cfg[0], datasets)
        else:
            self._data_lines(mask, panel, layer, cfg[0], datasets, cyclic=True)
        return mask

    def _fill_levels_expr(self, style: dict) -> str:
        vmin, vmax = style.get("vmin"), style.get("vmax")
        n = style.get("levels", 21)
        if isinstance(n, int):
            if vmin is not None and vmax is not None:
                self.needs_numpy = True
                return f"np.linspace({vmin!r}, {vmax!r}, {n!r})"
            return repr(n)
        return repr(require_increasing_levels(n))

    def _pcolormesh_levels_expr(self, style: dict, da_var: str,
                                contourf_trim=False) -> str:
        """pcolormesh + BoundaryNorm 用のレベル列を文字列で返す。

        levels がリスト (境界値の直接指定) ならそのまま、int (分割数) なら
        vmin/vmax (無ければ生成スクリプトでも da.min()/da.max()) から
        linspace で作る (render._fill_pcolormesh_kwargs と1対1対応)。
        contourf_trim=True (zero_white の contourf 経路) では int レベルの
        端を fill_zero_white_trim の slice で切り落とす。
        """
        n = style.get("levels", 21)
        if not isinstance(n, int):
            return repr(require_increasing_levels(n))
        self.needs_numpy = True
        vmin_src = (repr(style["vmin"]) if style.get("vmin") is not None
                    else f"float({da_var}.min())")
        vmax_src = (repr(style["vmax"]) if style.get("vmax") is not None
                    else f"float({da_var}.max())")
        expr = f"np.linspace({vmin_src}, {vmax_src}, {int(n)!r})"
        if contourf_trim:
            i0, i1 = fill_zero_white_trim(style.get("extend", "both"), int(n))
            if (i0, i1) != (0, int(n)):
                expr += f"[{i0}:{i1}]"
        return expr

