    def dist_panel(self, panel: dict, datasets: dict):
        """1次元プロット(集計)。render._render_dist_1d と1対1対応。"""
        body = self.body
        body.append(f"ax = fig.add_subplot({self._subplot_args()})")
        self._emit_box_aspect(panel)
        use_ax2 = dist_uses_secondary_axis(panel)
        if use_ax2:
            body.append("ax2 = ax.twinx()")
            ba = panel.get("box_aspect")
            if ba is not None:
                # twinx した両方に当てないと左右の枠がずれる (render と同じ)
                body.append(f"ax2.set_box_aspect({float(ba)!r})")
        body.append("")
        dist_horizontal = panel.get("box_orientation") == "horizontal"
        series_pos = 0
        for layer in panel["layers"]:
            kind = layer["kind"]
            target = ("ax2" if (use_ax2
                                and layer.get("style", {}).get("secondary_y")
                                and kind in ("line", "ecdf")) else "ax")
            if kind == "hist":
                self.hist_layer(panel, layer, datasets)
            elif kind == "ecdf":
                self.ecdf_layer(panel, layer, datasets, target)
            elif kind == "line":
                self.dist_line_layer(panel, layer, datasets, target)
            elif kind == "box":
                series_pos += 1
                self.box_layer(panel, layer, datasets, series_pos,
                               horizontal=dist_horizontal)
            elif kind == "violin":
                series_pos += 1
                self.violin_layer(panel, layer, datasets, series_pos,
                                  horizontal=dist_horizontal)
            else:
                raise NotImplementedError(f"Unsupported layer kind: {kind}")
        axis_cfg = panel.get("axis", {})
        # box/violin の系列名を系列軸の目盛に (render と同条件・同順)
        series_labels = dist_series_labels(panel)
        if series_labels:
            if dist_horizontal:
                if (axis_cfg.get("y_tick_interval") is None
                        and axis_cfg.get("y_tick_positions") is None):
                    body.append(
                        f"ax.set_yticks(range(1, {len(series_labels) + 1}))")
                    body.append(f"ax.set_yticklabels({series_labels!r})")
            elif (axis_cfg.get("x_tick_interval") is None
                  and axis_cfg.get("x_tick_positions") is None):
                body.append(
                    f"ax.set_xticks(range(1, {len(series_labels) + 1}))")
                body.append(f"ax.set_xticklabels({series_labels!r})")
            # 系列軸の範囲を固定 (render と同条件。1系列の幅が見えない問題の対策)
            if dist_horizontal:
                if not axis_cfg.get("y_lim"):
                    body.append(
                        f"ax.set_ylim(0.5, {len(series_labels)} + 0.5)")
            elif not axis_cfg.get("x_lim"):
                body.append(f"ax.set_xlim(0.5, {len(series_labels)} + 0.5)")
        # 縦軸の左右入れ替え: 第1軸→右は _tick_settings_lines が emit する。
        # 第2軸 (twinx) → 左だけここで emit (render と1対1)
        if axis_cfg.get("swap_y_sides") and use_ax2:
            body.append("ax2.yaxis.tick_left()")
            body.append("ax2.yaxis.set_label_position('left')")
        self._grid_lines(axis_cfg)
        self._log_scale_lines(axis_cfg, scalar_formatter=False)
        self._minor_tick_lines(axis_cfg)
        # 軸ラベルは自動フォールバック込みで生成時に確定 (render と同じ解決)
        xlab, ylab = dist_axis_labels(panel, datasets)
        label_base = self._axis_label_lines(axis_cfg, xlab, ylab)
        # 目盛設定は対数軸の後 (明示指定した目盛位置を優先、render と同順)
        self._tick_settings_lines(axis_cfg)
        self._invert_limit_lines(axis_cfg)
        # 第2軸の体裁 (render と同順)
        if use_ax2:
            if axis_cfg.get("y2_label"):
                args = ", ".join([repr(axis_cfg["y2_label"])]
                                  + [f"{k}={v!r}" for k, v in label_base.items()])
                body.append(f"ax2.set_ylabel({args})")
            if axis_cfg.get("y2_lim"):
                body.append(f"ax2.set_ylim({tuple(axis_cfg['y2_lim'])!r})")
            if axis_cfg.get("tick_fontsize"):
                body.append(
                    f"ax2.tick_params(labelsize={axis_cfg['tick_fontsize']!r})")
        self._frame_background_lines(panel)
        if use_ax2:
            # 図枠は ax2 にも当てる (render と1対1。背景は base ax 側のみ)
            self._frame_lines(panel, "ax2")
        self._legend_lines(panel.get("legend", {}), use_ax2)
        self._offset_suppress_lines(use_ax2)
        self._finish_panel_lines(panel)

    def _dist_value_lines(self, layer: dict, datasets: dict) -> str:
        """集計対象の 1次元配列 `_hv` を作る行を emit する (hist/ecdf 共用)。

        render.dist_values と1対1対応 (selection → agg_range → 値変換 →
        ravel → NaN 除去)。
        """
        body = self.body
        dsid = layer["dataset_id"]
        ds = datasets[dsid]
        var = layer["variable"]
        da = self._name("da_h")
        sel = {d: v for d, v in (layer.get("selection") or {}).items()
               if d in ds[var].dims}
        expr = f"{dsid}[{var!r}]"
        if sel:
            expr += ".sel(" + ", ".join(
                self._sel_arg(d, v) for d, v in sel.items()) + ")"
        body.append(f"{da} = {expr}")
        rng = layer.get("agg_range")
        dim = layer.get("agg_dim")
        if rng is not None and dim and dim in ds[var].dims:
            sl = coord_slice(ds[dim], rng[0], rng[1])
            body.append(f"{da} = {da}.sel({dim}=slice("
                        f"{sl.start!r}, {sl.stop!r}))")
        vt = _value_transform_line(da, layer["style"])
        if vt:
            body.append(vt)
        body.append(f"_hv = np.asarray({da}.values, dtype=float).ravel()")
        body.append("_hv = _hv[np.isfinite(_hv)]")
        return "_hv"

