    def line_bundle_layer(self, panel: dict, layer: dict, datasets: dict,
                          target: str = "ax"):
        """ライン (束)。render._bundle_layer_data / _draw_line_bundle_layer と1対1対応。

        bundle_dim は固定も平均もせず (panel.selection にあっても除外)、
        (x_dim, bundle_dim) に transpose してから列ごとに ax.plot する。
        凡例ラベルは 1 本目だけ。統計線は numpy の nan* 関数で列方向に集計する。
        """
        da = self._name("da_bundle")
        variable = layer["variable"]
        x_dim = panel["x_dim"]
        bdim = layer.get("bundle_dim")
        ds = datasets[layer["dataset_id"]]
        if not bdim or bdim not in ds[variable].dims or bdim == x_dim:
            raise ValueError(
                f"line_bundle layer needs a bundle_dim other than x_dim {x_dim!r} "
                f"among dims of {variable!r}: got {bdim!r}")
        panel_b = {**panel, "selection": {d: v for d, v in (panel.get("selection") or {}).items()
                                          if d != bdim}}
        sel = {d: v for d, v in (layer.get("selection") or {}).items() if d != bdim}
        avg = {d: c for d, c in (layer.get("averages") or {}).items() if d != bdim}
        self._emit_line_data(da, panel_b, layer, variable, datasets,
                             selection_override=sel, averages_override=avg)
        self.body.append(f"{da} = {da}.transpose({x_dim!r}, {bdim!r})")
        style = layer["style"]
        vt = _value_transform_line(da, style)
        if vt:
            self.body.append(vt)
        x = self._name("x_bundle")
        y = self._name("y_bundle")
        self.body.append(f"{x} = {da}[{x_dim!r}].values")
        self.body.append(f"{y} = {da}.values  # ({x_dim}, {bdim})")
        kw_str = _fmt_kwargs_inline(bundle_line_kwargs(style))
        label = style.get("label") or None
        label_str = f"label=({label!r} if _k == 0 else None), " if label else ""
        if bundle_lines_visible(style, 0.8):   # 太さ 0 = 束の線を描かない (render と同条件)
            self.body.append(f"for _k in range({y}.shape[1]):")
            self.body.append(f"    {target}.plot({x}, {y}[:, _k], {label_str}{kw_str})")
        for summary in layer.get("summaries") or []:
            self.needs_numpy = True
            s_style = summary.get("style") or {}
            s_kw = _fmt_kwargs_inline(bundle_stat_kwargs(s_style))
            s_label = s_style.get("label") or None
            lab = f"label={s_label!r}, " if s_label else ""
            exprs = [bundle_stat_expr(y, fn, q) for fn, q in bundle_stat_specs(summary)]
            draw = bundle_summary_draw(summary)
            lines_on = bundle_lines_visible(s_style, 2.0)   # 太さ 0 = 線を描かない
            if draw == "lines":
                if lines_on:
                    for j, expr in enumerate(exprs):
                        self.body.append(
                            f"{target}.plot({x}, {expr}, {lab if j == 0 else ''}{s_kw})")
            else:
                # 帯 (render と同順: fill_between → band_lines なら縁の線)
                band_kw = _fmt_kwargs_inline(bundle_band_kwargs(s_style))
                self.body.append(
                    f"{target}.fill_between({x}, {exprs[0]}, {exprs[1]}, {lab}{band_kw})")
                if draw == "band_lines" and lines_on:
                    for expr in exprs:
                        self.body.append(f"{target}.plot({x}, {expr}, {s_kw})")
        self.body.append("")

    def bar_layer(self, panel: dict, layer: dict, datasets: dict,
                   bar_state: dict, target: str = "ax"):
        """棒グラフレイヤー。bar_state は line_panel が管理する共通状態
        (n: 全 bar 数, mode: overlap/dodge/stack, idx: 0始まりの bar 番号,
         base_w_emitted: _bar_base_w を宣言済みか)。
        target は描画先 ("ax" / 第2軸 "ax2")。
        """
        da = self._name("da_bar")
        variable = layer["variable"]
        x_dim = panel["x_dim"]
        style = layer["style"]
        self._emit_line_data(da, panel, layer, variable, datasets)
        vt = _value_transform_line(da, style)
        if vt:
            self.body.append(vt)

        n = bar_state["n"]
        k = bar_state["idx"]
        mode = bar_state["mode"]
        # 一度だけ自動幅 _bar_base_w を宣言 (stack なら累積も初期化)
        if not bar_state["base_w_emitted"]:
            self.needs_numpy = True
            self.body.append(
                f"_bar_x = {da}[{x_dim!r}].values")
            self.body.append(
                "_bar_base_w = (np.median(np.diff(_bar_x)) * 0.8 "
                "if len(_bar_x) > 1 else 1.0)")
            if mode == "stack":
                self.body.append(
                    f"_bar_cum_pos = np.zeros({da}.values.shape, dtype=float)")
                self.body.append(
                    f"_bar_cum_neg = np.zeros({da}.values.shape, dtype=float)")
            bar_state["base_w_emitted"] = True

        manual_w = style.get("width")
        full_w_expr = repr(manual_w) if manual_w is not None else "_bar_base_w"
        if mode == "dodge":
            # render._compute_bar_params と同じ計算
            gap = max(0.0, min(0.5, float(
                panel.get("axis", {}).get("bar_dodge_gap", 0.05))))
            slot_expr = f"(({full_w_expr}) / {n!r})"
            width_expr = f"({slot_expr} * {(1.0 - gap)!r})"
            offset_expr = f"(({k!r} - ({n!r} - 1) / 2.0) * {slot_expr})"
            pos_expr = f"({da}[{x_dim!r}].values + {offset_expr})"
            bottom_expr = None
        elif mode == "stack":
            width_expr = full_w_expr
            pos_expr = f"{da}[{x_dim!r}].values"
            bottom_expr = (
                f"np.where({da}.values >= 0, _bar_cum_pos, _bar_cum_neg).copy()")
        else:  # overlap
            width_expr = full_w_expr
            pos_expr = f"{da}[{x_dim!r}].values"
            bottom_expr = None

        kw = {"color": style.get("color", "#1f77b4"),
              "alpha": float(style.get("alpha", 0.8))}
        edge_on = float(style.get("edge_linewidth", 0.0)) > 0
        hatch_on = bool(style.get("hatch_pattern"))
        if edge_on:
            kw["edgecolor"] = style.get("edge_color", "#000000")
            kw["linewidth"] = float(style["edge_linewidth"])
        elif hatch_on:
            kw["edgecolor"] = style.get("hatch_color", "#000000")
            kw["linewidth"] = 0.0
        if hatch_on:
            kw["hatch"] = (str(style["hatch_pattern"])
                            * int(style.get("hatch_density", 3)))
        if style.get("label"):
            kw["label"] = style["label"]
        # エラーバー: yerr/xerr は値が式 (リテラルでない) になりうるので
        # 文字列で別途追加
        err_kw_parts = []
        err_cfg = style.get("errorbar", {})
        err_src = err_cfg.get("source", "none")
        err_axis_name = ("xerr" if style.get("orientation") == "horizontal"
                          else "yerr")
        if err_src == "variable" and err_cfg.get("variable"):
            self.needs_numpy = True
            err_da = self._name("da_bar_err")
            self._emit_line_data(err_da, panel, layer,
                                  err_cfg["variable"], datasets)
            err_vt = _value_transform_line(err_da, style)
            if err_vt:
                self.body.append(err_vt)
            err_kw_parts.append(f"{err_axis_name}=np.abs({err_da}.values)")
        elif err_src == "constant":
            c = float(err_cfg.get("constant", 0.0))
            if c != 0:
                err_kw_parts.append(f"{err_axis_name}={abs(c)!r}")
        if err_kw_parts:
            err_kw_parts.append(f"ecolor={err_cfg.get('color', '#000000')!r}")
            err_kw_parts.append(f"capsize={float(err_cfg.get('capsize', 3.0))!r}")
            elw = float(err_cfg.get("linewidth", 1.0))
            if elw != 1.0:
                err_kw_parts.append(f"error_kw={{'elinewidth': {elw!r}}}")
        kw_str = ", ".join([f"{key}={val!r}" for key, val in kw.items()]
                            + err_kw_parts)

        orientation = style.get("orientation", "vertical")
        if orientation == "horizontal":
            if bottom_expr:
                self.body.append(
                    f"{target}.barh({pos_expr}, {da}.values, "
                    f"height={width_expr}, left={bottom_expr}, {kw_str})")
            else:
                self.body.append(
                    f"{target}.barh({pos_expr}, {da}.values, "
                    f"height={width_expr}, {kw_str})")
        else:
            if bottom_expr:
                self.body.append(
                    f"{target}.bar({pos_expr}, {da}.values, "
                    f"width={width_expr}, bottom={bottom_expr}, {kw_str})")
            else:
                self.body.append(
                    f"{target}.bar({pos_expr}, {da}.values, "
                    f"width={width_expr}, {kw_str})")

        if mode == "stack":
            self.body.append(
                f"_bar_cum_pos = _bar_cum_pos + np.where("
                f"{da}.values > 0, {da}.values, 0.0)")
            self.body.append(
                f"_bar_cum_neg = _bar_cum_neg + np.where("
                f"{da}.values < 0, {da}.values, 0.0)")
        self.body.append("")
        bar_state["idx"] += 1

