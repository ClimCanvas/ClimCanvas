    def _scatter_take_lines(self, tag: str, dsid: str, ds, var: str, fixed,
                            drawing_dim, drawing_range, scale: float,
                            offset: float = 0.0, *, err: bool = False) -> str:
        """散布図・バブル図の1変数を切り出す行を emit し、1次元 float 配列の式を返す。
        render._scatter_take_values と1対1対応 (err=True は誤差配列: 倍率のみ・|err|)。"""
        name = self._name(f"da_{tag}")
        sel = {dim: val for dim, val in (fixed or {}).items()
                if dim in ds[var].dims}
        expr = f"{dsid}[{var!r}]"
        if sel:
            expr += ".sel(" + ", ".join(
                self._sel_arg(d, v) for d, v in sel.items()) + ")"
        self.body.append(f"{name} = {expr}")
        if drawing_range and drawing_dim and drawing_dim in ds[var].dims:
            sl = coord_slice(ds[drawing_dim], drawing_range[0], drawing_range[1])
            self.body.append(
                f"{name} = {name}.sel({drawing_dim}=slice("
                f"{sl.start!r}, {sl.stop!r}))")
        if err:
            return (f"np.abs(np.asarray({name}.values, dtype=float)"
                    f" * {scale!r}).ravel()")
        if scale != 1.0 or offset != 0.0:
            # 括弧が無いと .ravel() がオフセットのリテラルに掛かる
            return (f"(np.asarray({name}.values, dtype=float)"
                    f" * {scale!r} + {offset!r}).ravel()")
        return f"np.asarray({name}.values, dtype=float).ravel()"

    def _scatter_error_lines(self, prefix: str, tag: str, dsid: str, ds,
                             layer: dict, style: dict, drawing_dim,
                             drawing_range) -> tuple[bool, bool]:
        """エラーバーの誤差配列 `{prefix}_xe` / `{prefix}_ye` の行を emit する。
        render._scatter_error_arrays + _fit_error_to_mask と1対1対応 (本体と同じ
        固定・範囲、倍率のみ、本体と同じ mask)。(x あり, y あり) を返す。"""
        eb = style.get("errorbar") or {}
        emitted = []
        for axis, var_key, fixed_key, scale_key in (
                ("x", "x_variable", "x_fixed", "x_value_scale"),
                ("y", "y_variable", "y_fixed", "y_value_scale")):
            var = eb.get(var_key)
            if not var or var not in ds:
                emitted.append(False)
                continue
            name = f"{prefix}_{axis}e"
            self.body.append(f"{name} = " + self._scatter_take_lines(
                tag, dsid, ds, var, layer.get(fixed_key), drawing_dim, drawing_range,
                float(style.get(scale_key, 1.0)), err=True))
            self.body.append(
                f"{name} = np.concatenate([{name}[:{prefix}_n], "
                f"np.full(max(0, {prefix}_n - len({name})), np.nan)])[{prefix}_mask]")
            emitted.append(True)
        return emitted[0], emitted[1]

    def _scatter_xy_lines(self, panel: dict, layer: dict, datasets: dict):
        """散布図/hexbin の x/y 抽出コードを emit する (`_sc_x` / `_sc_y` を作る)。

        render._scatter_xy_arrays と1対1対応。scatter_layer と hexbin_layer で共用。
        戻り値はエラーバーの誤差配列 (`_sc_xe` / `_sc_ye`) を出したかの (x, y)。
        """
        dsid = layer["dataset_id"]
        ds = datasets[dsid]
        style = layer["style"]
        drawing_dim = layer.get("drawing_dim")
        drawing_range = layer.get("drawing_range")
        x_expr, y_expr = (
            self._scatter_take_lines(
                "sc", dsid, ds, panel.get(f"{a}_variable"), layer.get(f"{a}_fixed"),
                drawing_dim, drawing_range,
                float(style.get(f"{a}_value_scale", 1.0)),
                float(style.get(f"{a}_value_offset", 0.0)))
            for a in ("x", "y"))
        # 直接ローカル変数に代入してから NaN マスク
        self.body.append(f"_sc_x = {x_expr}")
        self.body.append(f"_sc_y = {y_expr}")
        self.body.append("_sc_n = min(len(_sc_x), len(_sc_y))")
        self.body.append("_sc_x, _sc_y = _sc_x[:_sc_n], _sc_y[:_sc_n]")
        self.body.append("_sc_mask = ~(np.isnan(_sc_x) | np.isnan(_sc_y))")
        self.body.append("_sc_x, _sc_y = _sc_x[_sc_mask], _sc_y[_sc_mask]")
        # エラーバーの誤差配列 (hexbin は errorbar キーが無いので出ない)
        return self._scatter_error_lines("_sc", "sce", dsid, ds, layer, style,
                                         drawing_dim, drawing_range)

    def scatter_layer(self, panel: dict, layer: dict, datasets: dict):
        """散布図レイヤー。panel.x_variable / panel.y_variable をそれぞれ
        layer.x_fixed / y_fixed で固定して drawing_dim 沿いに ravel する。
        """
        self.needs_numpy = True
        style = layer["style"]
        has_xe, has_ye = self._scatter_xy_lines(panel, layer, datasets)
        if has_xe or has_ye:
            # エラーバーは点より先に描いて点を上に (render と同順)
            ekw = _fmt_kwargs_inline(errorbar_kwargs(
                style.get("errorbar") or {}))
            xarg = "_sc_xe" if has_xe else "None"
            yarg = "_sc_ye" if has_ye else "None"
            self.body.append(
                f"ax.errorbar(_sc_x, _sc_y, xerr={xarg}, yerr={yarg}, {ekw})")

        kw_str = _fmt_kwargs_inline(scatter_marker_kwargs(style))
        self.body.append(f"ax.scatter(_sc_x, _sc_y, {kw_str})")
        self.body.append("")

