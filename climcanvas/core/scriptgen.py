    def _transform_and_mask_lines(self, da: str, panel: dict, layer: dict,
                                  datasets: dict, *, section: bool) -> None:
        """値変換 → maskout の行。render._transform_and_mask と1対1対応。"""
        style = layer["style"]
        vt = _value_transform_line(da, style)
        if vt:
            self.body.append(vt)
        _mv = self._maskout_mask_lines(panel, layer, datasets, style,
                                       section=section)
