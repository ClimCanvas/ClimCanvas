    def stream_section_layer(self, panel: dict, layer: dict, datasets: dict):
        """断面図の流線。render._draw_stream_section と1対1対応。

        streamplot は昇順・等間隔の座標を要求するため、必要な軸だけ
        `.interp()` で等間隔グリッドへ線形補間する行を出力する
        (どの軸に補間が要るかは生成時にデータを見て判定する)。
        """
        u = self._name("u_st")
        v = self._name("v_st")
        sp = self._name("sp")
        self._section_data_lines(u, panel, layer, layer["u_variable"], datasets)
        self._section_data_lines(v, panel, layer, layer["v_variable"], datasets,
                                 dataset_id=vector_v_dataset_id(layer))
        style = layer["style"]
        for name in (u, v):
            vt = _value_transform_line(name, style)
            if vt:
                self.body.append(vt)
        # 等間隔化の要否を render と同じ判定 (stream_uniform_coords) で決める。
        # 判定にはデータが必要なので、render と同じ選択・平均を適用した
        # DataArray を生成時にも作って座標を見る
        ds = datasets[layer["dataset_id"]]
        selection = {**(panel.get("selection") or {}),
                     **(layer.get("selection") or {})}
        da = select_section_data(ds, layer["u_variable"], selection,
                                 panel.get("ranges"), panel["x_dim"],
                                 panel["y_dim"], averages=layer.get("averages"))
        for dim in (panel["x_dim"], panel["y_dim"]):
            uni = stream_uniform_coords(da[dim].values)
            if uni is not None:
                self.needs_numpy = True
                lo, hi, n = float(uni[0]), float(uni[-1]), uni.size
                grid = f"np.linspace({lo!r}, {hi!r}, {n!r})"
                self.body.append(
                    f"# streamplot needs ascending, evenly spaced coords (interpolating {dim})")
                self.body.append(f"{u} = {u}.interp({dim}={grid})")
                self.body.append(f"{v} = {v}.interp({dim}={grid})")
        skw = stream_kwargs(style)
        color_line, norm_line, norm_expr = self._stream_color_lines(style, u, v,
                                                                    skw)
        self.body += [
            f"{sp} = ax.streamplot(",
            f"    {u}[{panel['x_dim']!r}].values, {u}[{panel['y_dim']!r}].values, "
            f"{u}.values, {v}.values,",
            *_fmt_kwargs_lines(skw),
            *color_line,
            *norm_line,
            ")",
        ]
        mappable = self._stream_clim_lines(sp, style, norm_expr)
        if mappable is not None:
            self._colorbar_lines(mappable, style.get("colorbar", {}),
                                 extend=continuous_cbar_extend(style))
        self.body.append("")

    def map_scatter_layer(self, panel: dict, layer: dict, datasets: dict):
        """地図の散布図。render._draw_map_scatter と1対1対応。

        格子データ / 地点データの分岐は**生成時に確定**し、該当する抽出コードだけ
        を emit する (lon/lat が変数の次元なら格子、そうでなければ地点)。
        """
        self.needs_numpy = True
        dsid = layer["dataset_id"]
        ds = datasets[dsid]
        roles = detect_coord_roles(ds)
        lon_name, lat_name = roles["lon"], roles["lat"]
        var = layer["variable"]
        style = layer["style"]
        da = self._name("da_ms")
        hdims = horizontal_dims(ds, roles)
        if hdims is not None and all(d in ds[var].dims for d in hdims):
            # 格子データ: _data_lines が selection+region+transpose(lat,lon)
            self._data_lines(da, panel, layer, var, datasets)
            vt = _value_transform_line(da, style)
            if vt:
                self.body.append(vt)
            if is_curvilinear(ds, roles):
                # 2 次元座標はそのまま平坦化 (render.map_scatter_points と同じ)
                self.body += [
                    f"_ms_lon = np.asarray({da}[{lon_name!r}].values, "
                    f"dtype=float).ravel()",
                    f"_ms_lat = np.asarray({da}[{lat_name!r}].values, "
                    f"dtype=float).ravel()",
                ]
            else:
                self.body += [
                    f"_lon2d, _lat2d = np.meshgrid({da}[{lon_name!r}].values, "
                    f"{da}[{lat_name!r}].values)",
                    "_ms_lon = _lon2d.ravel()",
                    "_ms_lat = _lat2d.ravel()",
                ]
            self.body.append(
                f"_ms_val = np.asarray({da}.values, dtype=float).ravel()")
        else:
            # 地点データ: selection のみ、lon/lat は補助座標をそのまま
            selection = {**(panel.get("selection") or {}),
                         **(layer.get("selection") or {})}
            sel = {d: v for d, v in selection.items() if d in ds[var].dims}
            expr = f"{dsid}[{var!r}]"
            if sel:
                expr += ".sel(" + ", ".join(
                    self._sel_arg(d, v) for d, v in sel.items()) + ")"
            self.body.append(f"{da} = {expr}")
            vt = _value_transform_line(da, style)
            if vt:
                self.body.append(vt)
            self.body += [
                f"_ms_lon = np.asarray({dsid}[{lon_name!r}].values, "
                f"dtype=float).ravel()",
                f"_ms_lat = np.asarray({dsid}[{lat_name!r}].values, "
                f"dtype=float).ravel()",
                f"_ms_val = np.asarray({da}.values, dtype=float).ravel()",
            ]
        self.body += [
            "_ms_mask = ~(np.isnan(_ms_lon) | np.isnan(_ms_lat) "
            "| np.isnan(_ms_val))",
            "_ms_lon, _ms_lat, _ms_val = "
            "_ms_lon[_ms_mask], _ms_lat[_ms_mask], _ms_val[_ms_mask]",
        ]
        base = _fmt_kwargs_inline(map_scatter_kwargs(
            style, foreground=panel_land_foreground(panel)))
        if bool(style.get("use_cmap")):
            sc = self._name("sc")
            cmap = resolve_cmap(style.get("cmap", "viridis"),
                                style.get("reverse_cmap", False))
            cmap_expr, norm_expr = self._discrete_color_exprs(style, "_ms_val")
            kw = f"{base}, c=_ms_val, cmap={cmap_expr or repr(cmap)}"
            if norm_expr:
                kw += f", norm={norm_expr}"
            else:
                if style.get("vmin") is not None:
                    kw += f", vmin={float(style['vmin'])!r}"
                if style.get("vmax") is not None:
                    kw += f", vmax={float(style['vmax'])!r}"
            self.body.append(
                f"{sc} = ax.scatter(_ms_lon, _ms_lat, {kw}, "
                "transform=ccrs.PlateCarree())")
            if style.get("colorbar", {}).get("show", True):
                self._register_map_cbar(
                    self._colorbar_lines(sc, style.get("colorbar", {}),
                                         extend=continuous_cbar_extend(style)),
                    style.get("colorbar", {}))
        else:
            self.body.append(
                f"ax.scatter(_ms_lon, _ms_lat, {base}, "
                f"c={style.get('color', '#1f77b4')!r}, "
                "transform=ccrs.PlateCarree())")
        self.body.append("")

    def track_layer(self, panel: dict, layer: dict, datasets: dict):
        """トラック (軌跡)。render._draw_track と1対1対応。

        トラック毎の線は for ループで emit し (全 IBTrACS のような多数トラック
        でもスクリプトが肥大しない)、観測点は全トラック分をリストに貯めて
        最後に1回の scatter を emit する (render と同じ構成)。
        """
        self.needs_numpy = True
        body = self.body
        dsid = layer["dataset_id"]
        ds = datasets[dsid]
        style = layer["style"]
        pts = style.get("points") or {}
        every = max(1, int(pts.get("every", 1)))
        show_pts = bool(pts.get("show", True))
        use_val = bool(pts.get("variable"))
        stride = f"[::{every}]" if every != 1 else ""
        land_fg = panel_land_foreground(panel)
        line_kw = _fmt_kwargs_inline(track_line_kwargs(style))
        idxs = track_storm_indices(layer, datasets)
        sdim = layer.get("storm_dim")
        multi = not (len(idxs) == 1 and idxs[0] is None)

        def _take_expr(var, isel):
            expr = f"{dsid}[{var!r}]"
            if isel and sdim in ds[var].dims:
                expr += f".isel({sdim}=_si)"
            return expr

        mo = style.get("maskout") or {}
        mo_below, mo_above = mo.get("below"), mo.get("above")
        use_maskout = bool(mo.get("variable")
                           and (mo_below is not None or mo_above is not None))

        def _emit_track_body(indent, isel):
            """1本分の _lon/_lat/(_val) 抽出 + maskout + ax.plot を emit する。"""
            body.append(f"{indent}_lon = np.asarray("
                        f"{_take_expr(layer['lon_var'], isel)}.values, "
                        "dtype=float).ravel()")
            body.append(f"{indent}_lat = np.asarray("
                        f"{_take_expr(layer['lat_var'], isel)}.values, "
                        "dtype=float).ravel()")
            if show_pts and use_val:
                body.append(f"{indent}_v = {_take_expr(pts['variable'], isel)}")
                vt = _value_transform_line("_v", pts)
                if vt:
                    body.append(f"{indent}{vt}")
                body.append(f"{indent}_val = np.asarray(_v.values, "
                            "dtype=float).ravel()")
            if use_maskout:
                # render.track_arrays の maskout と同条件・同順
                body.append(f"{indent}_mv = np.asarray("
                            f"{_take_expr(mo['variable'], isel)}.values, "
                            "dtype=float).ravel()")
                conds = []
                if mo_below is not None:
                    conds.append(f"(_mv > {float(mo_below)!r})")
                if mo_above is not None:
                    conds.append(f"(_mv < {float(mo_above)!r})")
                body.append(f"{indent}_keep = " + " & ".join(conds))
                body.append(f"{indent}_lon = np.where(_keep, _lon, np.nan)")
                body.append(f"{indent}_lat = np.where(_keep, _lat, np.nan)")
                if show_pts and use_val:
                    body.append(f"{indent}_val = np.where(_keep, _val, np.nan)")
            body.append(f"{indent}ax.plot(_lon, _lat, {line_kw}, "
                        "transform=ccrs.Geodetic())")

        if multi and not idxs:
            body.append("# Tracks: nothing drawn (no tracks match the selection)")
            body.append("")
            return
        # 発生年・月フィルタ (render.track_storm_indices と同条件・同ロジック)
        use_filter = (multi and layer.get("time_var")
                      and layer["time_var"] in ds.variables
                      and (layer.get("year_range") or layer.get("month_range")))
        if multi:
            if use_filter:
                tv = layer["time_var"]
                others = [d for d in ds[tv].dims if d != sdim]
                if others:
                    body.append(f"_tr_gen = {dsid}[{tv!r}].min({others!r}, "
                                "skipna=True)")
                else:
                    body.append(f"_tr_gen = {dsid}[{tv!r}]")
                body.append("_tr_ok = ~np.isnat(_tr_gen.values)")
                yr_rng = layer.get("year_range")
                if yr_rng:
                    body.append("_tr_yr = _tr_gen.values.astype("
                                "'datetime64[Y]').astype(int) + 1970")
                    body.append(f"_tr_ok &= (_tr_yr >= {int(yr_rng[0])}) "
                                f"& (_tr_yr <= {int(yr_rng[1])})")
                mo_rng = layer.get("month_range")
                if mo_rng:
                    m0, m1 = int(mo_rng[0]), int(mo_rng[1])
                    body.append("_tr_mo = _tr_gen.values.astype("
                                "'datetime64[M]').astype(int) % 12 + 1")
                    if m0 <= m1:
                        body.append(f"_tr_ok &= (_tr_mo >= {m0}) "
                                    f"& (_tr_mo <= {m1})")
                    else:  # 年またぎ (例 11→3)
                        body.append(f"_tr_ok &= (_tr_mo >= {m0}) "
                                    f"| (_tr_mo <= {m1})")
            if show_pts:
                body.append("_tr_lons, _tr_lats, _tr_vals = [], [], []")
            if use_filter:
                body.append("for _si in np.where(_tr_ok)[0]:")
            else:
                body.append(f"for _si in range({idxs[0]}, {idxs[-1] + 1}):")
            _emit_track_body("    ", isel=True)
            if show_pts:
                body.append(f"    _tr_lons.append(_lon{stride})")
                body.append(f"    _tr_lats.append(_lat{stride})")
                if use_val:
                    body.append(f"    _tr_vals.append(_val{stride})")
            if show_pts:
                body.append("_tr_lon = np.concatenate(_tr_lons)")
                body.append("_tr_lat = np.concatenate(_tr_lats)")
                if use_val:
                    body.append("_tr_val = np.concatenate(_tr_vals)")
        else:
            _emit_track_body("", isel=False)
            if show_pts:
                body.append(f"_tr_lon = _lon{stride}")
                body.append(f"_tr_lat = _lat{stride}")
                if use_val:
                    body.append(f"_tr_val = _val{stride}")
        if not show_pts:
            body.append("")
            return
        base = _fmt_kwargs_inline(track_point_kwargs(pts, foreground=land_fg))
        if use_val:
            body += [
                "_tr_mask = (np.isfinite(_tr_lon) & np.isfinite(_tr_lat) "
                "& np.isfinite(_tr_val))",
                "_tr_lon, _tr_lat, _tr_val = "
                "_tr_lon[_tr_mask], _tr_lat[_tr_mask], _tr_val[_tr_mask]",
            ]
            sc = self._name("sc_tr")
            cmap = resolve_cmap(pts.get("cmap", "viridis"),
                                pts.get("reverse_cmap", False))
            cmap_expr, norm_expr = self._discrete_color_exprs(pts, "_tr_val")
            kw = f"{base}, c=_tr_val, cmap={cmap_expr or repr(cmap)}"
            if norm_expr:
                kw += f", norm={norm_expr}"
            else:
                if pts.get("vmin") is not None:
                    kw += f", vmin={float(pts['vmin'])!r}"
                if pts.get("vmax") is not None:
                    kw += f", vmax={float(pts['vmax'])!r}"
            body.append(f"{sc} = ax.scatter(_tr_lon, _tr_lat, {kw}, "
                        "transform=ccrs.PlateCarree())")
            if pts.get("colorbar", {}).get("show", True):
                self._register_map_cbar(
                    self._colorbar_lines(sc, pts.get("colorbar", {}),
                                         extend=continuous_cbar_extend(pts)),
                    pts.get("colorbar", {}))
        else:
            body += [
                "_tr_mask = np.isfinite(_tr_lon) & np.isfinite(_tr_lat)",
                f"ax.scatter(_tr_lon[_tr_mask], _tr_lat[_tr_mask], {base}, "
                f"c={pts.get('color', '#333333')!r}, "
                "transform=ccrs.PlateCarree())",
            ]
        body.append("")

    def _discrete_levels_expr(self, style: dict, data_expr: str) -> str:
        """離散化レベル列の式を返す (levels 指定済みの前提)。

        list は境界値そのまま (昇順・重複除去済み)、int は vmin/vmax
        (未指定はデータ範囲) の linspace (render._discrete_level_array と
        1対1対応。data_expr は numpy 配列の式、例 "vmag" / "_bb_z")。
        """
        nlev = resolve_discrete_levels(style)
        if isinstance(nlev, list):
            return repr(nlev)
        self.needs_numpy = True
        vmin_src = (repr(style["vmin"]) if style.get("vmin") is not None
                    else f"float(np.nanmin({data_expr}))")
        vmax_src = (repr(style["vmax"]) if style.get("vmax") is not None
                    else f"float(np.nanmax({data_expr}))")
        return f"np.linspace({vmin_src}, {vmax_src}, {nlev!r})"

    def _discrete_norm_expr(self, style: dict, data_expr: str) -> str | None:
        """style["levels"] 指定時の BoundaryNorm 式を返す (連続なら None)。

        render.discrete_cmap_norm と1対1対応。`_lv = ...` 行を body に追加し、
        norm 式の文字列を返す。
        """
        if resolve_discrete_levels(style) is None:
            return None
        self.needs_mcolors = True
        self.body.append(f"_lv = {self._discrete_levels_expr(style, data_expr)}")
        cmap_name = resolve_cmap(style.get("cmap", "viridis"),
                                 style.get("reverse_cmap", False))
        # render.discrete_cmap_norm と同じ extend (neither は既定値なので省略)
        extend = style.get("extend", "neither")
        extend_arg = f", extend={extend!r}" if extend != "neither" else ""
        return (f"mcolors.BoundaryNorm(_lv, "
                f"ncolors=plt.get_cmap({cmap_name!r}).N{extend_arg})")

    def _zero_white_lines(self, style: dict, lv_expr: str, extend: str):
        """0 を含むビンを白にした _zwcm/_zwnorm の構築行を出す。

        render.zero_white_colors / discrete_color_kwargs と1対1対応。
        レベル列 lv_expr の各ビン (+extend の端ビン) に cmap の等間隔
        サンプリング色を割り当て、lv[i] <= 0 <= lv[i+1] のビンを白に置換する。
        """
        self.needs_numpy = True
        self.needs_mcolors = True
        cmap_name = resolve_cmap(style.get("cmap", "viridis"),
                                 style.get("reverse_cmap", False))
        n_low = 1 if extend in ("min", "both") else 0
        n_extra = n_low + (1 if extend in ("max", "both") else 0)
        self.body += [
            f"_lv = np.asarray({lv_expr}, dtype=float)",
            f"_zwcl = plt.get_cmap({cmap_name!r})("
            f"np.linspace(0.0, 1.0, len(_lv) - 1 + {n_extra}))",
            "for _i in range(len(_lv) - 1):",
            "    if _lv[_i] <= 0.0 <= _lv[_i + 1]:",
            f"        _zwcl[_i + {n_low}] = (1.0, 1.0, 1.0, 1.0)",
            "_zwcm = mcolors.ListedColormap(_zwcl)",
            f"_zwnorm = mcolors.BoundaryNorm(_lv, ncolors=len(_zwcl), "
            f"extend={extend!r})",
        ]

    def _discrete_color_exprs(self, style: dict,
                              data_expr: str) -> tuple[str | None, str | None]:
        """離散化の (cmap 式, norm 式) を返す (render.discrete_color_kwargs と1対1対応)。

        連続なら (None, None)。通常の離散化は (None, BoundaryNorm 式) で
        cmap は呼び出し側の解決のまま。zero_white 時は構築行を出して
        ("_zwcm", "_zwnorm") — 呼び出し側は cmap をこの式で上書きすること。
        """
        if not style.get("zero_white"):
            return None, self._discrete_norm_expr(style, data_expr)
        if resolve_discrete_levels(style) is None:
            return None, None
        self._zero_white_lines(style,
                               self._discrete_levels_expr(style, data_expr),
                               style.get("extend", "neither"))
        return "_zwcm", "_zwnorm"

    def _quiverkey_lines(self, q: str, key: dict, zorder=None):
        """render._draw_quiverkey() と同じ操作のコードを出力する。"""
        kx = key.get("x", 1.0)
        ky = key.get("y", -0.07)
        labelpos = key.get("labelpos", "E")
        label = key.get("label", "")
        pad = "      "
        # 文字サイズ未指定は引数を出さない (render と同じ分岐。旧 config の
        # 生成スクリプトを変えない)
        fontsize = key.get("fontsize")
        key_kw = f", fontproperties={{'size': {fontsize!r}}}" if fontsize else ""
        if zorder is not None:
            key_kw += f", zorder={zorder!r}"
        text_kw = f", fontsize={fontsize!r}" if fontsize else ""
        self.body.append(f"ax.quiverkey({q}, {kx!r}, {ky!r}, {key.get('length', 10.0)!r}, "
                         f"{label!r}, labelpos={labelpos!r}{key_kw})")
        self.body.append("# Dummy artist so QuiverKey is counted in bbox_inches='tight' margins")
        label_side, arrow_side = ("left", "right") if labelpos == "E" else ("right", "left")
        dummy = pad + label if labelpos == "E" else label + pad
        self.body.append(f"ax.text({kx!r}, {ky!r}, {dummy!r}, transform=ax.transAxes, "
                         f"ha={label_side!r}, va='center', alpha=0{text_kw})")
        self.body.append(f"ax.text({kx!r}, {ky!r}, {pad!r}, transform=ax.transAxes, "
                         f"ha={arrow_side!r}, va='center', alpha=0{text_kw})")

