    def _agg_xy_lines(self, panel: dict, layer: dict, datasets: dict) -> None:
        """agg_2d の (x, y) 標本ペア `_agx` / `_agy` を作る行を emit する。

        render.agg_xy_values と1対1対応 (固定 → transpose → float64 →
        値変換 → NaN ペア除去)。次元不一致は生成時に同じ ValueError。
        """
        ds = datasets[layer["dataset_id"]]
        style = layer["style"]
        body = self.body

        def _emit_take(var, fixed, tag):
            da = self._name(f"da_{tag}")
            sel = {d: v for d, v in (fixed or {}).items()
                   if d in ds[var].dims}
            expr = f"{layer['dataset_id']}[{var!r}]"
            if sel:
                expr += ".sel(" + ", ".join(
                    self._sel_arg(d, v) for d, v in sel.items()) + ")"
            body.append(f"{da} = {expr}")
            dims = tuple(d for d in ds[var].dims if d not in sel)
            return da, dims

        xname, xdims = _emit_take(panel["x_variable"], layer.get("x_fixed"), "agx")
        yname, ydims = _emit_take(panel["y_variable"], layer.get("y_fixed"), "agy")
        if set(xdims) != set(ydims):
            raise ValueError(
                "x/y variable dims do not match (fix the non-shared dims): "
                f"x={list(xdims)}, y={list(ydims)}")
        if xdims != ydims:
            args = ", ".join(repr(d) for d in xdims)
            body.append(f"{yname} = {yname}.transpose({args})")
        body.append(f"_agx = np.asarray({xname}.values, dtype=float).ravel()")
        body.append(f"_agy = np.asarray({yname}.values, dtype=float).ravel()")
        sx = float(style.get("x_value_scale", 1.0))
        ox = float(style.get("x_value_offset", 0.0))
        if sx != 1.0 or ox != 0.0:
            body.append(f"_agx = _agx * {sx!r} + {ox!r}")
        sy = float(style.get("y_value_scale", 1.0))
        oy = float(style.get("y_value_offset", 0.0))
        if sy != 1.0 or oy != 0.0:
            body.append(f"_agy = _agy * {sy!r} + {oy!r}")
        body.append("_agm = np.isfinite(_agx) & np.isfinite(_agy)")
        body.append("_agx, _agy = _agx[_agm], _agy[_agm]")

    def hist2d_layer(self, panel: dict, layer: dict, datasets: dict):
        """2次元ヒストグラム。render._draw_hist2d_layer と1対1対応。

        色の離散化 (levels) は描画後に集計結果 h[0] から BoundaryNorm を
        作って set_norm する (render と同じ後付け方式)。
        """
        self.needs_numpy = True
        style = layer["style"]
        self._agg_xy_lines(panel, layer, datasets)
        kw = _fmt_kwargs_inline(hist2d_kwargs(style))
        if style.get("log_counts"):
            self.needs_mcolors = True
            kw += (f", norm=mcolors.LogNorm(vmin={style.get('vmin')!r}, "
                   f"vmax={style.get('vmax')!r})")
        else:
            if style.get("vmin") is not None:
                kw += f", vmin={float(style['vmin'])!r}"
            if style.get("vmax") is not None:
                kw += f", vmax={float(style['vmax'])!r}"
        h = self._name("h2")
        self.body.append(f"{h} = ax.hist2d(_agx, _agy, {kw})")
        cmap_expr, norm_expr = self._discrete_color_exprs(style, f"{h}[0]")
        if cmap_expr:
            self.body.append(f"{h}[3].set_cmap({cmap_expr})")
        if norm_expr:
            self.body.append(f"{h}[3].set_norm({norm_expr})")
        if style.get("edge_width"):
            # render と1対1: cmin でマスクされたセルの枠線を消す
            edge = style.get("edge_color", "#000000")
            self.body.append(
                f"_h2mask = np.ma.getmaskarray({h}[3].get_array()).ravel()")
            self.body.append("if _h2mask.any():")
            self.body.append(
                f"    {h}[3].set_edgecolor(['none' if m else {edge!r} "
                "for m in _h2mask])")
        if style.get("colorbar", {}).get("show", True):
            self._colorbar_lines(f"{h}[3]", style.get("colorbar", {}),
                                 extend=continuous_cbar_extend(style))
        self.body.append("")

