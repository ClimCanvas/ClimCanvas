    def _match_colorbar_lines(self):
        """render.match_colorbars_to_axes() と同じ操作のコードを出力する。

        map_panel の末尾でパネル毎に呼ばれる。出力後に `_map_cbars` をクリアし、
        複数パネルで前パネルのカラーバーを再出力しないようにする。
        """
        if not self._map_cbars:
            return
        body = self.body
        body.append("")
        body.append("# Match colorbar length to the drawn map height (after aspect)")
        body.append("fig.canvas.draw()")
        body.append("pos = ax.get_position()")
        for cbar, cfg in self._map_cbars:
            shrink = cfg.get("shrink", 1.0) or 1.0
            cpos = self._name("cpos")
            body.append(f"{cpos} = {cbar}.ax.get_position()")
            body.append(f"{cbar}.ax.set_axes_locator(None)")
            if cfg.get("location", "right") in ("right", "left"):
                body.append(f"{cbar}.ax.set_position([{cpos}.x0, "
                            f"pos.y0 + pos.height * {(1 - shrink) / 2!r}, "
                            f"{cpos}.width, pos.height * {shrink!r}])")
            else:
                body.append(f"{cbar}.ax.set_position([pos.x0 + pos.width * {(1 - shrink) / 2!r}, "
                            f"{cpos}.y0, pos.width * {shrink!r}, {cpos}.height])")
        self._map_cbars = []

