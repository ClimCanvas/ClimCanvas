        for setter, lab, rot_key in (("set_xlabel", xlab, "x_label_rotation"),
                                     ("set_ylabel", ylab, "y_label_rotation")):
            if not lab:
                continue
            kw = dict(label_base)
            if axis_cfg.get(rot_key) is not None:
                kw["rotation"] = float(axis_cfg[rot_key])
            args = ", ".join([repr(lab)] + [f"{k}={v!r}" for k, v in kw.items()])
            self.body.append(f"ax.{setter}({args})")
        return label_base

