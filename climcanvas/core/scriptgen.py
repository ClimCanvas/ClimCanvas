    def fill_between_layer(self, panel: dict, layer: dict, datasets: dict,
                           target: str = "ax"):
        da_low = self._name("da_fb_low")
        variable = layer["variable"]
        x_dim = panel["x_dim"]
        style = layer["style"]
        self._emit_line_data(da_low, panel, layer, variable, datasets)
        vt = _value_transform_line(da_low, style)
        if vt:
            self.body.append(vt)
        var_upper = layer.get("variable_upper")
        color_above = style.get("color", "#1f77b4")
        color_below = style.get("color_below")
        alpha = float(style.get("alpha", 0.3))
        label = style.get("label")
        x_expr = f"{da_low}[{x_dim!r}].values"
        y_low_expr = f"{da_low}.values"
        if var_upper:
            da_high = self._name("da_fb_high")
            self._emit_line_data(
                da_high, panel, layer, var_upper, datasets,
                selection_override=layer.get("selection_upper") or {},
                averages_override=layer.get("averages_upper") or {})
            vt_high = _value_transform_line(da_high, style)
            if vt_high:
                self.body.append(vt_high)
            kw = {"color": color_above, "alpha": alpha}
            if label:
                kw["label"] = label
            kw_str = ", ".join(f"{k}={v!r}" for k, v in kw.items())
            self.body.append(
                f"{target}.fill_between({x_expr}, {y_low_expr}, "
                f"{da_high}.values, {kw_str})")
            self.body.append("")
            return
        # baseline モード
        baseline = float(layer.get("baseline", 0.0))
        if not color_below or color_below == color_above:
            kw = {"color": color_above, "alpha": alpha}
            if label:
                kw["label"] = label
            kw_str = ", ".join(f"{k}={v!r}" for k, v in kw.items())
            self.body.append(
                f"{target}.fill_between({x_expr}, {y_low_expr}, "
                f"{baseline!r}, {kw_str})")
            self.body.append("")
            return
        # 上下別色: where + interpolate=True (render._draw_fill_between_layer と同順)
        kw_above = {"color": color_above, "alpha": alpha, "interpolate": True}
        kw_below = {"color": color_below, "alpha": alpha, "interpolate": True}
        if label:
            kw_above["label"] = label
        kw_above_str = ", ".join(f"{k}={v!r}" for k, v in kw_above.items())
        kw_below_str = ", ".join(f"{k}={v!r}" for k, v in kw_below.items())
        self.body.append(
            f"{target}.fill_between({x_expr}, {y_low_expr}, {baseline!r}, "
            f"where=({y_low_expr} > {baseline!r}), {kw_above_str})")
        self.body.append(
            f"{target}.fill_between({x_expr}, {y_low_expr}, {baseline!r}, "
            f"where=({y_low_expr} < {baseline!r}), {kw_below_str})")
        self.body.append("")

    def _section_data_lines(self, name: str, panel: dict, layer: dict,
                            variable: str, datasets: dict,
                            dataset_id: str | None = None):
        """断面図用の切り出し行。dataset_id の意味は _data_lines と同じ
        (render._section_data と1対1対応)。"""
        dsid = dataset_id or layer["dataset_id"]
        ds = datasets[dsid]
        merged_selection = {**(panel.get("selection") or {}),
                            **(layer.get("selection") or {})}
        sel = {dim: val for dim, val in merged_selection.items()
               if dim in ds[variable].dims}
        expr = f"{dsid}[{variable!r}]"
        if sel:
            expr += ".sel(" + ", ".join(self._sel_arg(d, v) for d, v in sel.items()) + ")"
        self.body.append(f"{name} = {expr}")

        # render.apply_averages と1対1対応: selection の後、ranges の前で潰す
        averages = layer.get("averages") or {}
        self._emit_averages_lines(name, averages, ds, variable)

        for dim, bounds in (panel.get("ranges") or {}).items():
            if dim in ds[variable].dims and dim not in averages:
                sl = coord_slice(ds[dim], bounds[0], bounds[1])
                self.body.append(f"{name} = {name}.sel({dim}=slice({sl.start!r}, {sl.stop!r}))")
        self.body.append(f"{name} = {name}.transpose({panel['y_dim']!r}, {panel['x_dim']!r})")

    def _emit_averages_lines(self, name: str, averages: dict, ds, variable: str):
        """layer.averages を `.sel(...).mean(...)` の行に展開する共通ヘルパ。

        section と line 共用。経度の wrap-around / 冗長端点除去 / cos重み付きを含む。
        呼び出し側で x_dim 等を除外した averages を渡すこと。対象 dim の絞り込みは
        render.effective_averages、切り出しは render.averaging_slice と 1 対 1。
        """
        if not averages:
            return
        roles_local = detect_coord_roles(ds)
        lon_name = roles_local.get("lon")
        for dim, op_cfg in effective_averages(ds[variable].dims, averages).items():
            lo_user, hi_user = op_cfg["range"]
            if dim == lon_name:
                check_lon_range_covered(lo_user, hi_user, ds[dim].values)
                lo_n, hi_n, wrap, dmin, dmax = canon_lon_range_for_averaging(
                    lo_user, hi_user, ds[dim].values)
                if wrap:
                    sl1 = coord_slice(ds[dim], lo_n, dmax)
                    sl2 = coord_slice(ds[dim], dmin, hi_n)
                    self.body.append(
                        f"_p1 = {name}.sel({dim}=slice({sl1.start!r}, {sl1.stop!r}))")
                    self.body.append(
                        f"_p2 = {name}.sel({dim}=slice({sl2.start!r}, {sl2.stop!r}))")
                    if has_redundant_lon_endpoint(ds[dim].values):
                        self.body.append(
                            f"_p1 = _p1.isel({dim}=slice(None, -1))")
                    self.body.append(
                        f"{name} = xr.concat([_p1, _p2], dim={dim!r})")
                else:
                    sl = coord_slice(ds[dim], lo_n, hi_n)
                    self.body.append(
                        f"{name} = {name}.sel({dim}=slice({sl.start!r}, {sl.stop!r}))")
            else:
                sl = coord_slice(ds[dim], lo_user, hi_user)
                self.body.append(
                    f"{name} = {name}.sel({dim}=slice({sl.start!r}, {sl.stop!r}))")
            if op_cfg.get("op") == "weighted_mean":
                self.needs_numpy = True
                self.body.append(
                    f"_w = np.cos(np.deg2rad({name}[{dim!r}]))")
                self.body.append(
                    f"{name} = {name}.weighted(_w).mean(dim={dim!r})")
            else:
                self.body.append(f"{name} = {name}.mean(dim={dim!r})")

