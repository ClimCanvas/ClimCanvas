    def _grid_lines(self, axis_cfg: dict, *, legacy_show: bool = False) -> None:
        """目盛線。render._apply_axis_grid と1対1対応 (legacy_show は section_2d 用)。"""
        grid = axis_cfg.get("grid", {})
        fallback = grid.get("show", False) if legacy_show else False
        show_x = grid.get("show_x", fallback)
        show_y = grid.get("show_y", fallback)
        if show_x or show_y:
            which = "both" if (show_x and show_y) else ("x" if show_x else "y")
            self.body.append(
                f"ax.grid(axis={which!r}, color={grid.get('color', 'gray')!r}, "
                f"linewidth={grid.get('width', 0.5)!r}, "
                f"linestyle={grid.get('linestyle', ':')!r})")

