    def bubble_layer(self, panel: dict, layer: dict, datasets: dict):
        """バブルチャート: scatter_layer と同形で x/y/z を抽出、z を
        [size_min, size_max] に正規化して s= に渡す。
        """
        self.needs_numpy = True
        dsid = layer["dataset_id"]
        ds = datasets[dsid]
        style = layer["style"]
        drawing_dim = layer.get("drawing_dim")
        drawing_range = layer.get("drawing_range")
        x_expr, y_expr, z_expr = (
            self._scatter_take_lines(
                "bb", dsid, ds, panel.get(f"{a}_variable"), layer.get(f"{a}_fixed"),
                drawing_dim, drawing_range,
                float(style.get(f"{a}_value_scale", 1.0)),
                float(style.get(f"{a}_value_offset", 0.0)))
            for a in ("x", "y", "z"))
        self.body.append(f"_bb_x = {x_expr}")
        self.body.append(f"_bb_y = {y_expr}")
        self.body.append(f"_bb_z = {z_expr}")
        self.body.append("_bb_n = min(len(_bb_x), len(_bb_y), len(_bb_z))")
        self.body.append(
            "_bb_x, _bb_y, _bb_z = "
            "_bb_x[:_bb_n], _bb_y[:_bb_n], _bb_z[:_bb_n]")
        self.body.append(
            "_bb_mask = ~(np.isnan(_bb_x) | np.isnan(_bb_y) | np.isnan(_bb_z))")
        self.body.append(
            "_bb_x, _bb_y, _bb_z = "
            "_bb_x[_bb_mask], _bb_y[_bb_mask], _bb_z[_bb_mask]")
        # エラーバーの誤差配列 (render._bubble_xyz_arrays with_errors と1対1)
        has_xe, has_ye = self._scatter_error_lines("_bb", "bbe", dsid, ds, layer, style,
                                                   drawing_dim, drawing_range)
        if has_xe or has_ye:
            # エラーバーは点より先に描いて点を上に (render と同順)
            ekw = _fmt_kwargs_inline(errorbar_kwargs(style.get("errorbar") or {}))
            xarg = "_bb_xe" if has_xe else "None"
            yarg = "_bb_ye" if has_ye else "None"
            self.body.append(
                f"ax.errorbar(_bb_x, _bb_y, xerr={xarg}, yerr={yarg}, {ekw})")
        size_min = float(style.get("size_min", 10.0))
        size_max = float(style.get("size_max", 200.0))
        self.body.append(
            "if len(_bb_z) > 0:")
        self.body.append(
            "    _bb_zmin, _bb_zmax = float(_bb_z.min()), float(_bb_z.max())")
        self.body.append(
            f"    _bb_s = (np.full_like(_bb_z, ({size_min!r} + {size_max!r}) / 2.0) "
            f"if (_bb_zmax - _bb_zmin) < 1e-12 "
            f"else {size_min!r} + (_bb_z - _bb_zmin) / "
            f"(_bb_zmax - _bb_zmin) * ({size_max!r} - {size_min!r}))")
        self.body.append("else:")
        self.body.append("    _bb_s = _bb_z")
        use_cmap = bool(style.get("use_cmap"))
        kw = {"alpha": float(style.get("alpha", 0.6)),
              "marker": style.get("marker", "o")}
        extra_args = []
        bb_norm_expr = None
        if use_cmap:
            cmap_name = resolve_cmap(style.get("cmap", "viridis"),
                                       style.get("reverse_cmap", False))
            bb_cmap_expr, bb_norm_expr = self._discrete_color_exprs(style,
                                                                    "_bb_z")
            if bb_cmap_expr:
                extra_args.append(f"cmap={bb_cmap_expr}")
            else:
                kw["cmap"] = cmap_name
            if bb_norm_expr is None:
                # norm と vmin/vmax は同時指定不可 (render と同じ分岐)
                if style.get("vmin") is not None:
                    kw["vmin"] = float(style["vmin"])
                if style.get("vmax") is not None:
                    kw["vmax"] = float(style["vmax"])
            extra_args.append("c=_bb_z")
            if bb_norm_expr:
                extra_args.append(f"norm={bb_norm_expr}")
        else:
            kw["c"] = style.get("color", "#1f77b4")
        if float(style.get("edge_linewidth", 0.0)) > 0:
            kw["edgecolors"] = style.get("edge_color", "#000000")
            kw["linewidths"] = float(style["edge_linewidth"])
        if style.get("label"):
            kw["label"] = style["label"]
        kw_str = ", ".join([f"{k}={v!r}" for k, v in kw.items()] + extra_args)
        if use_cmap:
            self.body.append(f"_bb_sc = ax.scatter(_bb_x, _bb_y, s=_bb_s, {kw_str})")
            self._colorbar_lines("_bb_sc", style.get("colorbar", {}),
                                 extend=continuous_cbar_extend(style))
        else:
            self.body.append(f"ax.scatter(_bb_x, _bb_y, s=_bb_s, {kw_str})")
        self.body.append("")

