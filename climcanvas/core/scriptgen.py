    def line_panel(self, panel: dict, datasets: dict):
        """1次元プロット。render._render_line_1d と1対1対応。"""
        body = self.body
        body.append(f"ax = fig.add_subplot({self._subplot_args()})")
        self._emit_box_aspect(panel)
        use_ax2 = line_uses_secondary_axis(panel)
        if use_ax2:
            body.append("ax2 = ax.twinx()")
            ba = panel.get("box_aspect")
            if ba is not None:
                # twinx した両方に当てないと左右の枠がずれる (render と同じ)
                body.append(f"ax2.set_box_aspect({float(ba)!r})")
        body.append("")

        bar_state = {
            "n": sum(1 for lyr in panel["layers"] if lyr["kind"] == "bar"),
            "mode": panel.get("axis", {}).get("bar_mode", "overlap"),
            "idx": 0,
            "base_w_emitted": False,  # _bar_base_w を一度だけ宣言する
        }

        for layer in panel["layers"]:
            kind = layer["kind"]
            # 描画先 (render と同条件): secondary_y のレイヤーは第2軸
            target = ("ax2" if (use_ax2
                                and layer.get("style", {}).get("secondary_y"))
                      else "ax")
            if kind == "line":
                self.line_layer(panel, layer, datasets, target)
            elif kind == "line_bundle":
                self.line_bundle_layer(panel, layer, datasets, target)
            elif kind == "fill_between":
                self.fill_between_layer(panel, layer, datasets, target)
            elif kind == "stackplot":
                self.stackplot_layer(panel, layer, datasets, target)
            elif kind == "bar":
                self.bar_layer(panel, layer, datasets, bar_state, target)
            else:
                raise NotImplementedError(f"Unsupported layer kind: {kind}")

        axis_cfg = panel.get("axis", {})
        self._grid_lines(axis_cfg)
        self._minor_tick_lines(axis_cfg)
        label_base = self._axis_label_lines(axis_cfg, axis_cfg.get("x_label"),
                                            axis_cfg.get("y_label"))
        self._log_scale_lines(axis_cfg, scalar_formatter=True)
        # 目盛設定は対数軸の後 (明示指定した目盛位置を優先、render と同順)
        self._tick_settings_lines(axis_cfg)
        # 余白除去は invert / x_lim より前 (render.py と同順)
        if axis_cfg.get("tight_x") and not axis_cfg.get("x_lim"):
            body.append("ax.autoscale(axis='x', tight=True)")
        if axis_cfg.get("tight_y") and not axis_cfg.get("y_lim"):
            body.append("ax.autoscale(axis='y', tight=True)")
        self._invert_limit_lines(axis_cfg)
        # 第2軸 (twinx) の体裁 (render と同順)
        if use_ax2:
            self._secondary_axis_lines(axis_cfg, label_base)
            v_align = twin_align_value(axis_cfg)
            if v_align is not None:
                # 指定値の高さを左右で揃える (render と1対1。関数本体は冒頭に埋め込む)
                self.needs_twin_align = True
                body.append(f"_l1, _l2 = align_twin_ylim(ax.get_ylim(), "
                            f"ax2.get_ylim(), {v_align!r})")
                body.append("ax.set_ylim(_l1)")
                body.append("ax2.set_ylim(_l2)")

        fmt = axis_cfg.get("time_axis_format")
        if fmt and panel.get("layers") and panel.get("x_dim"):
            ds = datasets[panel["layers"][0]["dataset_id"]]
            time_dim = detect_coord_roles(ds).get("time")
            if time_dim and panel["x_dim"] == time_dim:
                self.needs_mdates = True
                body.append(f"ax.xaxis.set_major_formatter(mdates.DateFormatter({fmt!r}))")

        self._frame_background_lines(panel)
        if use_ax2:
            # 図枠は ax2 にも当てる (render と1対1。背景は base ax 側のみ)
            self._frame_lines(panel, "ax2")
        self._legend_lines(panel.get("legend", {}), use_ax2)
        self._offset_suppress_lines(use_ax2)
        self._finish_panel_lines(panel)

    def _emit_line_data(self, name: str, panel: dict, layer: dict,
                         variable: str, datasets: dict,
                         *, selection_override: dict | None = None,
                         averages_override: dict | None = None) -> None:
        """1変数を sel/tile して `name = ...` を body に追加する共通ヘルパ。

        render._line_layer_data と一対一で対応すること。line_layer と
        fill_between_layer の両方から呼ばれる。selection_override / averages_override
        は var_upper 用に layer.selection_upper / layer.averages_upper を渡すために使う。
        """
        dsid = layer["dataset_id"]
        ds = datasets[dsid]
        x_dim = panel["x_dim"]
        axis_cfg = panel.get("axis", {})
        ranges = panel.get("ranges") or {}
        cyclic_x_active = (axis_cfg.get("cyclic_x") and x_dim in ranges
                            and x_dim in ds[variable].dims)
        # panel.selection (時刻) と layer.selection (lat/lon/level 等) をマージ、
        # x_dim は selection から除外
        layer_sel = selection_override if selection_override is not None \
            else (layer.get("selection") or {})
        layer_avg = averages_override if averages_override is not None \
            else (layer.get("averages") or {})
        merged_selection = {**(panel.get("selection") or {}), **layer_sel}
        sel = {dim: val for dim, val in merged_selection.items()
                if dim in ds[variable].dims and dim != x_dim}
        expr = f"{dsid}[{variable!r}]"
        if sel:
            expr += ".sel(" + ", ".join(self._sel_arg(d, v) for d, v in sel.items()) + ")"
        self.body.append(f"{name} = {expr}")

        # averages を selection の直後・cyclic/ranges より前に適用
        # (x_dim は averages から除外。tile/sel は averages 後の dim に対する操作)
        avg_non_x = effective_averages(ds[variable].dims, layer_avg, exclude=(x_dim,))
        self._emit_averages_lines(name, avg_non_x, ds, variable)

        if cyclic_x_active:
            # cyclic 拡張: render.cyclic_tile_lon と同じ操作 (360° 周期で繰り返し)
            self.needs_numpy = True
            x_lo, x_hi = float(ranges[x_dim][0]), float(ranges[x_dim][1])
            x_arr = np.asarray(ds[x_dim].values)
            x_min_data, x_max_data = float(x_arr.min()), float(x_arr.max())
            period = 360.0
            n_right = min(10, max(0, int(np.ceil((x_hi - x_max_data) / period))))
            n_left = min(10, max(0, int(np.ceil((x_min_data - x_lo) / period))))
            if n_right > 0 or n_left > 0:
                self.body.append(f"_x_orig = {name}[{x_dim!r}].values")
                self.body.append(
                    f"_tiles = [({name} if _k == 0 "
                    f"else {name}.assign_coords({x_dim}=_x_orig + _k * {period!r})) "
                    f"for _k in range({-n_left!r}, {n_right + 1!r})]")
                self.body.append(f"{name} = xr.concat(_tiles, dim={x_dim!r})")
            self.body.append(
                f"{name} = {name}.sel({x_dim}=slice({x_lo!r}, {x_hi!r}))")
            # x_dim 以外の range は通常通り適用
            for dim, bounds in ranges.items():
                if dim == x_dim or dim not in ds[variable].dims:
                    continue
                sl = coord_slice(ds[dim], bounds[0], bounds[1])
                self.body.append(
                    f"{name} = {name}.sel({dim}=slice({sl.start!r}, {sl.stop!r}))")
        else:
            for dim, bounds in ranges.items():
                if dim in ds[variable].dims:
                    sl = coord_slice(ds[dim], bounds[0], bounds[1])
                    self.body.append(
                        f"{name} = {name}.sel({dim}=slice({sl.start!r}, {sl.stop!r}))")

